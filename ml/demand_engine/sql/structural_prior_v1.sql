-- Beyond Live Demand Engine — Structural Prior v1
--
-- The Structural Prior is the validated historical champion carried forward
-- between business checkpoints. This contract never falls back silently to
-- older Lech-only historical forecasts.

create table if not exists private.structural_prior_model_specs_v1 (
    horizon text not null,
    target_days_before integer not null,
    model_spec_id text not null,
    model_family text not null,
    feature_contract text not null,
    validation_report text not null,
    status text not null default 'historical_champion_candidate',
    is_current boolean not null default false,
    activated_at timestamptz not null default now(),
    notes text,
    primary key(horizon,model_spec_id),
    constraint structural_prior_model_specs_v1_horizon_ck
      check(horizon in ('T-30','T-14','T-7','T-3','T-1')),
    constraint structural_prior_model_specs_v1_days_ck
      check(target_days_before in (30,14,7,3,1))
);

create unique index if not exists structural_prior_model_specs_v1_current_uq
  on private.structural_prior_model_specs_v1(horizon)
  where is_current;

