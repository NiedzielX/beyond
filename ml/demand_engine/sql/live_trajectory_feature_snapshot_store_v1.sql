-- Beyond Live Demand Engine — append-only point-in-time feature evidence store v1

create table if not exists private.live_trajectory_feature_snapshots_v1 (
    id bigint generated by default as identity primary key,
    ticket_event_id bigint not null references public.ticket_events(id),
    horizon text not null,
    as_of_at timestamptz not null,
    kickoff_at timestamptz not null,
    feature_version text not null,
    source_snapshot_id bigint not null references public.snapshots(id),
    source_snapshot_captured_at timestamptz not null,
    signal_readiness text not null,
    feature_quality text not null,
    point_in_time_validated boolean not null,
    training_eligible boolean generated always as (
        point_in_time_validated and signal_readiness='ready'
    ) stored,
    features jsonb not null,
    source_metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    constraint live_trajectory_feature_snapshots_v1_pit_ck
      check (source_snapshot_captured_at <= as_of_at),
    constraint live_trajectory_feature_snapshots_v1_time_ck
      check (as_of_at < kickoff_at),
    constraint live_trajectory_feature_snapshots_v1_signal_ck
      check (signal_readiness in ('not_ready','partial','ready')),
    constraint live_trajectory_feature_snapshots_v1_uq
      unique(ticket_event_id,horizon,as_of_at,feature_version,source_snapshot_id)
);

create index if not exists live_trajectory_feature_snapshots_v1_event_idx
  on private.live_trajectory_feature_snapshots_v1(ticket_event_id,as_of_at);

create index if not exists live_trajectory_feature_snapshots_v1_training_idx
  on private.live_trajectory_feature_snapshots_v1(horizon,feature_version,training_eligible,as_of_at);

comment on table private.live_trajectory_feature_snapshots_v1 is
'Append-only evidence store for leakage-safe Live Demand Engine feature rows. A later source backfill creates a new evidence row rather than overwriting prior training evidence.';

create or replace view private.current_live_trajectory_feature_snapshots_v1 as
select distinct on (ticket_event_id,horizon,as_of_at,feature_version)
    *
from private.live_trajectory_feature_snapshots_v1
order by ticket_event_id,horizon,as_of_at,feature_version,created_at desc,id desc;

comment on view private.current_live_trajectory_feature_snapshots_v1 is
'Latest materialization for each event/horizon/as-of/feature-version while preserving immutable prior evidence rows.';

create or replace function private.materialize_live_trajectory_feature_snapshot_v1(
    p_ticket_event_id bigint,
    p_as_of_at timestamptz,
    p_horizon text default 'continuous',
    p_stadium_capacity integer default null
)
returns bigint
language plpgsql
security definer
set search_path=private,public
as $function$
declare
    v_row record;
    v_id bigint;
begin
    select * into v_row
    from public.get_live_trajectory_features_v1_1_asof(
        p_ticket_event_id,p_as_of_at,p_stadium_capacity
    );

    if v_row.snapshot_id is null then
        return null;
    end if;
    if v_row.snapshot_captured_at > p_as_of_at then
        raise exception 'point-in-time violation: source snapshot % is after as_of %',
            v_row.snapshot_captured_at,p_as_of_at;
    end if;
    if p_as_of_at >= v_row.kickoff_at then
        raise exception 'as_of_at must be before kickoff';
    end if;

    insert into private.live_trajectory_feature_snapshots_v1(
        ticket_event_id,horizon,as_of_at,kickoff_at,feature_version,
        source_snapshot_id,source_snapshot_captured_at,signal_readiness,
        feature_quality,point_in_time_validated,features,source_metadata
    ) values (
        p_ticket_event_id,p_horizon,p_as_of_at,v_row.kickoff_at,v_row.feature_version,
        v_row.snapshot_id,v_row.snapshot_captured_at,v_row.signal_readiness,
        v_row.feature_quality,v_row.point_in_time_validated,to_jsonb(v_row),
        jsonb_build_object(
            'generator','get_live_trajectory_features_v1_1_asof',
            'stadium_capacity_input',p_stadium_capacity,
            'materialization_contract','live-feature-snapshot-store-v1'
        )
    )
    on conflict(ticket_event_id,horizon,as_of_at,feature_version,source_snapshot_id)
    do nothing
    returning id into v_id;

    if v_id is null then
        select id into v_id
        from private.live_trajectory_feature_snapshots_v1
        where ticket_event_id=p_ticket_event_id
          and horizon=p_horizon
          and as_of_at=p_as_of_at
          and feature_version=v_row.feature_version
          and source_snapshot_id=v_row.snapshot_id;
    end if;
    return v_id;
end;
$function$;

comment on function private.materialize_live_trajectory_feature_snapshot_v1(bigint,timestamptz,text,integer) is
'Materializes one immutable live-trajectory-v1.1 feature evidence row. Returns existing id on idempotent replay.';

create or replace function private.materialize_due_live_trajectory_checkpoints_v1()
returns integer
language plpgsql
security definer
set search_path=private,public
as $function$
declare
    v_record record;
    v_id bigint;
    v_count integer:=0;
begin
    for v_record in
        select ticket_event_id,horizon,target_as_of_at
        from private.ticketing_horizon_readiness_v2_1
        where checkpoint_due
          and snapshot_id is not null
        order by target_as_of_at,ticket_event_id,horizon
    loop
        v_id:=private.materialize_live_trajectory_feature_snapshot_v1(
            v_record.ticket_event_id,
            v_record.target_as_of_at,
            v_record.horizon,
            null
        );
        if v_id is not null then
            v_count:=v_count+1;
        end if;
    end loop;
    return v_count;
end;
$function$;

comment on function private.materialize_due_live_trajectory_checkpoints_v1() is
'Idempotently materializes all due exact-cutoff T-30/T-14/T-7/T-3/T-1 live trajectory rows currently supported by raw evidence.';
