"""Canonical daily trajectory dataset builder for Beyond.

This module does not fit a model. It materializes one leakage-safe event/cutoff
row per requested P-N horizon and deliberately reuses the existing canonical
``live_trajectory_feature_store`` instead of defining a second trajectory
semantics.

Public inventory is a demand proxy, not confirmed paid ticket sales.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Iterable

from .live_trajectory_feature_store import (
    INVENTORY_INTERPRETATION,
    LiveTrajectoryFeatures,
    SectorInventoryRecord,
    SnapshotRecord,
    build_live_trajectory_features,
)
from .structural_prior import StructuralPrior

DATASET_VERSION = "daily-trajectory-dataset-v1"
DEFAULT_START_DAYS = 60
DEFAULT_END_DAYS = 1


@dataclass(frozen=True)
class DailyTrajectoryRow:
    """One point-in-time event/cutoff row.

    ``trajectory`` is always present. When no usable snapshot exists by the
    cutoff the canonical feature store returns ``feature_quality=no_usable_snapshot``
    and the row is intentionally preserved rather than interpolated away.
    """

    dataset_version: str
    ticket_event_id: int
    club_slug: str
    kickoff_at: datetime
    days_to_event: int
    as_of_at: datetime
    inventory_interpretation: str
    trajectory: LiveTrajectoryFeatures
    structural_prior: StructuralPrior | None
    occupied_capacity_proxy: int | None
    structural_prior_available: bool
    residual_model_input_ready: bool
    point_in_time_validated: bool = True
    target_future_points_used: bool = False


def build_daily_trajectory_dataset(
    *,
    ticket_event_id: int,
    club_slug: str,
    kickoff_at: datetime,
    snapshots: Iterable[SnapshotRecord],
    sectors: Iterable[SectorInventoryRecord] = (),
    structural_priors: Iterable[StructuralPrior] = (),
    stadium_capacity: int | None = None,
    public_seat_map_size: int | None = None,
    start_days: int = DEFAULT_START_DAYS,
    end_days: int = DEFAULT_END_DAYS,
) -> tuple[DailyTrajectoryRow, ...]:
    """Build canonical P-N rows from ``start_days`` down to ``end_days``.

    Each row is built independently at its exact daily cutoff:

    ``as_of_at = kickoff_at - timedelta(days=N)``

    The underlying trajectory feature builder sees the full raw snapshot list
    but itself filters strictly to ``captured_at <= as_of_at``. Structural
    priors are also selected only if they were requested and generated by the
    cutoff. No future observation is used to complete an earlier row.
    """
    _require_aware("kickoff_at", kickoff_at)
    if ticket_event_id <= 0:
        raise ValueError("ticket_event_id must be positive")
    if not club_slug.strip():
        raise ValueError("club_slug must not be empty")
    if start_days < end_days:
        raise ValueError("start_days must be >= end_days")
    if end_days < 1:
        raise ValueError("end_days must be >= 1")
    if stadium_capacity is not None and stadium_capacity <= 0:
        raise ValueError("stadium_capacity must be positive")

    snapshot_rows = tuple(snapshots)
    sector_rows = tuple(sectors)
    prior_rows = tuple(structural_priors)

    rows: list[DailyTrajectoryRow] = []
    for days_to_event in range(start_days, end_days - 1, -1):
        as_of_at = kickoff_at - timedelta(days=days_to_event)
        trajectory = build_live_trajectory_features(
            snapshot_rows,
            sector_rows,
            as_of=as_of_at,
            kickoff_at=kickoff_at,
            stadium_capacity=stadium_capacity,
            public_seat_map_size=public_seat_map_size,
        )
        prior = select_structural_prior_at_cutoff(
            prior_rows,
            ticket_event_id=ticket_event_id,
            as_of_at=as_of_at,
        )

        occupied_proxy: int | None = None
        if stadium_capacity is not None and trajectory.available_total is not None:
            # This is deliberately named a proxy. Publicly unavailable inventory
            # is not equivalent to paid sales or final attendance.
            occupied_proxy = max(0, stadium_capacity - trajectory.available_total)

        rows.append(
            DailyTrajectoryRow(
                dataset_version=DATASET_VERSION,
                ticket_event_id=ticket_event_id,
                club_slug=club_slug,
                kickoff_at=kickoff_at,
                days_to_event=days_to_event,
                as_of_at=as_of_at,
                inventory_interpretation=INVENTORY_INTERPRETATION,
                trajectory=trajectory,
                structural_prior=prior,
                occupied_capacity_proxy=occupied_proxy,
                structural_prior_available=prior is not None,
                residual_model_input_ready=(
                    prior is not None
                    and trajectory.available_total is not None
                    and trajectory.point_in_time_validated
                ),
            )
        )

    return tuple(rows)


def select_structural_prior_at_cutoff(
    priors: Iterable[StructuralPrior],
    *,
    ticket_event_id: int,
    as_of_at: datetime,
) -> StructuralPrior | None:
    """Select the latest structural prior genuinely available by ``as_of_at``.

    A prior is eligible only when:

    - it belongs to the same event;
    - it is point-in-time validated;
    - its target checkpoint is not in the future;
    - its original request time is not in the future;
    - it has a real ``generated_at`` timestamp and was generated by the cutoff.

    Requiring ``generated_at`` prevents a later reconstruction of an old
    checkpoint from masquerading as information that existed historically.
    """
    _require_aware("as_of_at", as_of_at)
    eligible: list[StructuralPrior] = []

    for prior in priors:
        if prior.ticket_event_id != ticket_event_id:
            continue
        if not prior.point_in_time_validated:
            continue
        _require_aware("prior.target_as_of_at", prior.target_as_of_at)
        _require_aware("prior.requested_as_of_at", prior.requested_as_of_at)
        if prior.generated_at is None:
            continue
        _require_aware("prior.generated_at", prior.generated_at)
        if prior.target_as_of_at > as_of_at:
            continue
        if prior.requested_as_of_at > as_of_at:
            continue
        if prior.generated_at > as_of_at:
            continue
        prior.validate()
        eligible.append(prior)

    if not eligible:
        return None

    return max(
        eligible,
        key=lambda prior: (
            prior.requested_as_of_at,
            prior.target_as_of_at,
            prior.generated_at or prior.target_as_of_at,
            prior.source_prior_id or -1,
        ),
    )


def _require_aware(name: str, value: datetime) -> None:
    if value.tzinfo is None or value.utcoffset() is None:
        raise ValueError(f"{name} must be timezone-aware")
