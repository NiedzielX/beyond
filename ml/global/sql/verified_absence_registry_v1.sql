-- Beyond Ticketing — verified absence registry v1.
--
-- Discovery/verification stays evidence-based. Once an absence is verified, the
-- registry automatically propagates it to matching future fixtures.
-- Missing registry entry = unknown, never confirmed available.
-- No demand-impact score is emitted unless player salience, certainty and
-- novelty are all supported.

alter table public.context_feature_definitions
  drop constraint if exists context_feature_definitions_collection_status_check;

alter table public.context_feature_definitions
  add constraint context_feature_definitions_collection_status_check
  check (collection_status is null or collection_status in (
    'active_automated','active_manual','verified_registry',
    'shadow_automated','planned','blocked_external_access'
  ));

create table if not exists public.sporting_verified_absences (
  id bigint generated by default as identity primary key,
  team_name text not null,
  team_key text not null,
  player_name text not null,
  absence_status text not null,
  reason text not null,
  reported_recovery text,
  source_name text not null,
  source_url text not null,
  source_published_at timestamptz,
  confidence numeric(5,4) not null check (confidence >= 0 and confidence <= 1),
  absence_certainty numeric(5,4) check (absence_certainty is null or (absence_certainty >= 0 and absence_certainty <= 1)),
  novelty numeric(5,4) check (novelty is null or (novelty >= 0 and novelty <= 1)),
  player_salience numeric(5,4) check (player_salience is null or (player_salience >= 0 and player_salience <= 1)),
  valid_from timestamptz not null,
  valid_until timestamptz,
  review_due_at timestamptz,
  is_active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (valid_until is null or valid_until > valid_from),
  unique(team_key, player_name, valid_from)
);

create index if not exists idx_sporting_verified_absences_team_active
  on public.sporting_verified_absences(team_key,is_active,valid_from,valid_until);
create index if not exists idx_sporting_verified_absences_review
  on public.sporting_verified_absences(review_due_at) where is_active;

alter table public.sporting_verified_absences enable row level security;
revoke all on public.sporting_verified_absences from anon, authenticated;
grant select,insert,update,delete on public.sporting_verified_absences to service_role;
grant usage,select on sequence public.sporting_verified_absences_id_seq to service_role;

