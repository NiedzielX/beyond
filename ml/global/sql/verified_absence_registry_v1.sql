create or replace function public.refresh_verified_absence_context_v1()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_count integer := 0;
begin
  with applicable as (
    select
      e.id as ticket_event_id,
      a.id as absence_id,
      a.team_name,
      a.player_name,
      a.absence_status,
      a.reason,
      a.reported_recovery,
      a.source_name,
      a.source_url,
      a.source_published_at,
      a.confidence,
      a.absence_certainty,
      a.novelty,
      a.player_salience,
      a.valid_from,
      a.valid_until,
      a.review_due_at
    from public.ticket_events e
    join public.sporting_verified_absences a
      on a.is_active
     and a.valid_from <= e.kickoff_at
     and (a.valid_until is null or a.valid_until > e.kickoff_at)
     and a.team_key in (
       public.sporting_canonical_team_v1(e.home_team),
       public.sporting_canonical_team_v1(e.away_team)
     )
    where e.kickoff_at >= now()-interval '3 hours'
      and e.kickoff_at < now()+interval '120 days'
  ), grouped as (
    select
      ticket_event_id,
      min(confidence) as confidence,
      max(source_published_at) as source_observed_at,
      string_agg(
        format('%s: %s — %s; %s%s',
          team_name,
          player_name,
          replace(absence_status,'_',' '),
          reason,
          case when reported_recovery is not null
            then format(' (reported recovery: %s)',reported_recovery)
            else '' end
        ),
        ' | ' order by team_name,player_name
      ) as absence_summary,
      jsonb_agg(
        jsonb_build_object(
          'absence_id',absence_id,
          'team',team_name,
          'player',player_name,
          'status',absence_status,
          'reason',reason,
          'reported_recovery',reported_recovery,
          'source_name',source_name,
          'source_url',source_url,
          'source_published_at',source_published_at,
          'absence_certainty',absence_certainty,
          'novelty',novelty,
          'player_salience',player_salience,
          'valid_from',valid_from,
          'valid_until',valid_until,
          'review_due_at',review_due_at
        ) order by team_name,player_name
      ) as absences,
      bool_and(player_salience is not null) as all_salience_supported
    from applicable
    group by ticket_event_id
  )
  insert into public.event_context_observations(
    ticket_event_id,feature_key,observed_at,numeric_value,text_value,normalized_score,
    source_name,source_url,source_observed_at,confidence,source_record_key,metadata
  )
  select
    ticket_event_id,
    'sport.absence_impact',
    now(),
    null,
    absence_summary || '. Demand impact not scored unless player salience, certainty and novelty are all supported.',
    null,
    'Beyond verified absence register',
    null,
    source_observed_at,
    confidence,
    format('verified-absence-register:v01:event:%s',ticket_event_id),
    jsonb_build_object(
      'verified_absences',absences,
      'coverage_complete',false,
      'registry_status','verified_manual_input_automated_propagation',
      'player_importance_scored',all_salience_supported,
      'scoring_status',case when all_salience_supported
        then 'eligible_for_separate_demand_shock_review'
        else 'raw_verified_absence_only' end,
      'production_impact','none_context_research_only',
      'coverage_note','Register propagates known verified absences only. Missing player is unknown, not confirmed available.'
    )
  from grouped
  on conflict (ticket_event_id,feature_key,source_name,source_record_key)
  do update set
    observed_at=excluded.observed_at,
    numeric_value=excluded.numeric_value,
    text_value=excluded.text_value,
    source_observed_at=excluded.source_observed_at,
    confidence=excluded.confidence,
    metadata=excluded.metadata;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.refresh_verified_absence_context_v1() from public,anon,authenticated;
grant execute on function public.refresh_verified_absence_context_v1() to service_role;

update public.context_feature_definitions
set collection_status='verified_registry',
    primary_source='Beyond verified absence register backed by official club/competition evidence',
    fallback_source='Manual verified research for newly discovered or unresolved absences',
    collection_note='Absences are verified once from official evidence and stored with an active validity window; Beyond then propagates them automatically to matching future fixtures. The register does not infer player availability from silence, and an absence does not receive a demand score unless player salience, certainty and novelty are supported.',
    updated_at=now()
where feature_key='sport.absence_impact';

update public.context_feature_definitions
set collection_status='verified_registry',updated_at=now()
where feature_key='sport.rivalry_opponent';

do $$
declare v_job bigint;
begin
  select jobid into v_job from cron.job where jobname='verified_absence_context_daily';
  if v_job is not null then perform cron.unschedule(v_job); end if;
end $$;

select cron.schedule(
  'verified_absence_context_daily',
  '27 4 * * *',
  $$select public.refresh_verified_absence_context_v1();$$
);

select public.refresh_verified_absence_context_v1();
