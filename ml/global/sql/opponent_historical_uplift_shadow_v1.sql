-- Beyond Ticketing — opponent historical uplift shadow v1.
--
-- Research-only. Uses only verified attendance outcomes strictly before the
-- target kickoff. A score is emitted only when both history gates are met:
--   >= 8 prior home outcomes for the club in the same competition class,
--   >= 3 prior home meetings with the same opponent,
-- within a 730-day lookback.
-- Otherwise uplift stays NULL; insufficient history is not treated as zero.

create or replace function public.match_competition_key_v1(value text)
returns text
language sql
immutable
strict
as $$
  select case
    when value ilike '%Ekstraklasa%' then 'ekstraklasa'
    when value ilike '%Europa League%' then 'uefa_europa_league'
    when value ilike '%Champions League%' then 'uefa_champions_league'
    when value ilike '%Conference League%' then 'uefa_conference_league'
    else trim(regexp_replace(lower(value),'[^a-z0-9]+','_','g'),'_')
  end;
$$;

revoke all on function public.match_competition_key_v1(text) from public,anon,authenticated;
grant execute on function public.match_competition_key_v1(text) to service_role;

create table if not exists public.opponent_uplift_shadow_samples (
  id bigint generated by default as identity primary key,
  ticket_event_id bigint not null references public.ticket_events(id) on delete cascade,
  observed_at timestamptz not null,
  competition_key text not null,
  club_history_count integer not null,
  opponent_history_count integer not null,
  club_median_attendance numeric,
  opponent_median_attendance numeric,
  uplift_pct numeric,
  readiness_status text not null
    check (readiness_status in ('insufficient_club_history','insufficient_opponent_history','ready')),
  source_name text not null default 'Beyond attendance history',
  source_snapshot_key text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(ticket_event_id,source_snapshot_key)
);

create index if not exists idx_opponent_uplift_shadow_event_time
  on public.opponent_uplift_shadow_samples(ticket_event_id,observed_at desc);

alter table public.opponent_uplift_shadow_samples enable row level security;
revoke all on public.opponent_uplift_shadow_samples from anon,authenticated;
grant select,insert,update,delete on public.opponent_uplift_shadow_samples to service_role;
grant usage,select on sequence public.opponent_uplift_shadow_samples_id_seq to service_role;

create or replace function public.refresh_opponent_historical_uplift_shadow_v1()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_count integer := 0;
begin
  with targets as (
    select e.id,e.club_slug,e.home_team,e.away_team,e.kickoff_at,
      public.match_competition_key_v1(e.competition) as competition_key
    from public.ticket_events e
    where e.kickoff_at>=now()
      and e.kickoff_at<now()+interval '120 days'
  ), history as (
    select t.id as ticket_event_id,h.id as historical_event_id,h.away_team,
      o.actual_attendance,h.kickoff_at
    from targets t
    join public.ticket_events h
      on h.club_slug=t.club_slug
     and h.kickoff_at<t.kickoff_at
     and h.kickoff_at>=t.kickoff_at-interval '730 days'
     and public.match_competition_key_v1(h.competition)=t.competition_key
    join public.ticket_event_outcomes o on o.ticket_event_id=h.id
    where o.actual_attendance is not null
  ), stats as (
    select t.id as ticket_event_id,t.home_team,t.away_team,t.competition_key,
      count(h.historical_event_id)::int as club_history_count,
      count(h.historical_event_id) filter (
        where public.sporting_canonical_team_v1(h.away_team)=public.sporting_canonical_team_v1(t.away_team)
      )::int as opponent_history_count,
      percentile_cont(0.5) within group (order by h.actual_attendance)::numeric as club_median_attendance,
      percentile_cont(0.5) within group (order by h.actual_attendance) filter (
        where public.sporting_canonical_team_v1(h.away_team)=public.sporting_canonical_team_v1(t.away_team)
      )::numeric as opponent_median_attendance
    from targets t
    left join history h on h.ticket_event_id=t.id
    group by t.id,t.home_team,t.away_team,t.competition_key
  ), scored as (
    select *,
      case
        when club_history_count<8 then 'insufficient_club_history'
        when opponent_history_count<3 then 'insufficient_opponent_history'
        else 'ready'
      end as readiness_status,
      case
        when club_history_count>=8 and opponent_history_count>=3 and club_median_attendance>0
          then round(((opponent_median_attendance/club_median_attendance)-1.0)*100.0,2)
        else null
      end as uplift_pct
    from stats
  )
  insert into public.opponent_uplift_shadow_samples(
    ticket_event_id,observed_at,competition_key,club_history_count,opponent_history_count,
    club_median_attendance,opponent_median_attendance,uplift_pct,readiness_status,
    source_snapshot_key,metadata
  )
  select ticket_event_id,now(),competition_key,club_history_count,opponent_history_count,
    club_median_attendance,opponent_median_attendance,uplift_pct,readiness_status,
    format('opponent-uplift:v01:event:%s:%s',ticket_event_id,to_char(now() at time zone 'UTC','YYYYMMDD')),
    jsonb_build_object(
      'home_team',home_team,'away_team',away_team,'lookback_days',730,
      'club_history_gate',8,'opponent_history_gate',3,
      'statistic','median_attendance_ratio',
      'leakage_rule','only outcomes with kickoff before target kickoff',
      'production_impact','none_shadow_only'
    )
  from scored
  on conflict (ticket_event_id,source_snapshot_key)
  do update set
    observed_at=excluded.observed_at,
    competition_key=excluded.competition_key,
    club_history_count=excluded.club_history_count,
    opponent_history_count=excluded.opponent_history_count,
    club_median_attendance=excluded.club_median_attendance,
    opponent_median_attendance=excluded.opponent_median_attendance,
    uplift_pct=excluded.uplift_pct,
    readiness_status=excluded.readiness_status,
    metadata=excluded.metadata;

  get diagnostics v_count=row_count;

  insert into public.event_context_observations(
    ticket_event_id,feature_key,observed_at,numeric_value,text_value,normalized_score,
    source_name,source_observed_at,confidence,source_record_key,metadata
  )
  select s.ticket_event_id,'match.opponent_historical_uplift',s.observed_at,s.uplift_pct,
    format('Historyczny uplift frekwencji dla tego rywala: %s%%; %s wcześniejsze mecze z tym rywalem, %s mecze klubu w baseline.',
      to_char(s.uplift_pct,'FM999990.00'),s.opponent_history_count,s.club_history_count),
    null,'Beyond attendance history',s.observed_at,
    least(0.95,0.55+0.05*s.opponent_history_count),
    format('opponent-uplift:v01:event:%s:%s',s.ticket_event_id,to_char(s.observed_at at time zone 'UTC','YYYYMMDD')),
    s.metadata || jsonb_build_object(
      'club_history_count',s.club_history_count,
      'opponent_history_count',s.opponent_history_count,
      'club_median_attendance',s.club_median_attendance,
      'opponent_median_attendance',s.opponent_median_attendance,
      'readiness_status',s.readiness_status,
      'scoring_status','research_historical_uplift_not_model_active'
    )
  from public.opponent_uplift_shadow_samples s
  where s.observed_at::date=current_date
    and s.readiness_status='ready'
    and s.uplift_pct is not null
  on conflict (ticket_event_id,feature_key,source_name,source_record_key)
  do update set
    observed_at=excluded.observed_at,
    numeric_value=excluded.numeric_value,
    text_value=excluded.text_value,
    confidence=excluded.confidence,
    metadata=excluded.metadata;

  return v_count;
end;
$$;

revoke all on function public.refresh_opponent_historical_uplift_shadow_v1() from public,anon,authenticated;
grant execute on function public.refresh_opponent_historical_uplift_shadow_v1() to service_role;

drop view if exists public.dashboard_opponent_uplift_readiness_v1;
create view public.dashboard_opponent_uplift_readiness_v1
with (security_invoker=true)
as
select distinct on (s.ticket_event_id)
  s.ticket_event_id,e.home_team,e.away_team,e.kickoff_at,s.observed_at,
  s.competition_key,s.club_history_count,s.opponent_history_count,
  s.club_median_attendance,s.opponent_median_attendance,s.uplift_pct,s.readiness_status
from public.opponent_uplift_shadow_samples s
join public.ticket_events e on e.id=s.ticket_event_id
order by s.ticket_event_id,s.observed_at desc;

revoke all on public.dashboard_opponent_uplift_readiness_v1 from public;
grant select on public.dashboard_opponent_uplift_readiness_v1 to anon,authenticated,service_role;

update public.context_feature_definitions
set collection_status='shadow_automated',
    primary_source='Beyond verified attendance history',
    fallback_source='No score until history gate is met',
    refresh_cadence='daily + after verified attendance outcome',
    collection_note='Automated leakage-safe readiness gate uses only verified outcomes before the target kickoff, within the same home club and competition class. Uplift is emitted only after >=8 prior club outcomes and >=3 prior home meetings with the same opponent in a 730-day lookback; otherwise the value stays null rather than defaulting to zero.',
    updated_at=now()
where feature_key='match.opponent_historical_uplift';

do $$
declare v_job bigint;
begin
  select jobid into v_job from cron.job where jobname='opponent_uplift_shadow_daily';
  if v_job is not null then perform cron.unschedule(v_job); end if;
end $$;

select cron.schedule(
  'opponent_uplift_shadow_daily','37 4 * * *',
  $$select public.refresh_opponent_historical_uplift_shadow_v1();$$
);

select public.refresh_opponent_historical_uplift_shadow_v1();
