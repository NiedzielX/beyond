)
on public.sporting_context_shadow_samples to anon, authenticated;

create table if not exists public.sporting_round_fetch_requests (
  request_id bigint primary key,
  league_id text not null,
  season text not null,
  round_number integer not null check (round_number between 1 and 34),
  requested_at timestamptz not null default now(),
  processed_at timestamptz,
  status text not null default 'queued' check (status in ('queued','processed','error')),
  error_text text
);

create index if not exists idx_sporting_round_fetch_requests_status_time
  on public.sporting_round_fetch_requests(status, requested_at);

alter table public.sporting_round_fetch_requests enable row level security;
