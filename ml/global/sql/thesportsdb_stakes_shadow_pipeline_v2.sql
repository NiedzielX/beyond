create or replace function public.sporting_canonical_team_v1(value text)
returns text
language sql
immutable
strict
as $$
  select case
    when x = 'kghm zaglebie lubin' then 'zaglebie lubin'
    when x in ('legia warszawa','legia warsaw') then 'legia warsaw'
    else x
  end
  from (
    select trim(regexp_replace(
      translate(lower(value),'ąćęłńóśźż','acelnoszz'),
      '[^a-z0-9]+',' ','g'
    )) as x
  ) s;
$$;

revoke all on function public.sporting_canonical_team_v1(text) from public, anon, authenticated;
grant execute on function public.sporting_canonical_team_v1(text) to service_role;

create or replace function public.enqueue_thesportsdb_rounds_v1()
returns integer
language plpgsql
security invoker
set search_path=public,net,pg_temp
as $$
declare
  v_max_completed integer;
  v_start integer;
  v_end integer;
  v_round integer;
  v_request_id bigint;
  v_count integer := 0;
begin
  select max(round_number) into v_max_completed
  from public.sporting_league_matches_shadow
  where league_id='4422' and season='2026-2027' and completed=true;

  if v_max_completed is null then
    v_start := 1;
    v_end := 12;
  else
    v_start := greatest(1, v_max_completed - 1);
    v_end := least(34, v_max_completed + 2);
  end if;

  for v_round in v_start..v_end loop
    -- Do not add custom headers here. TheSportsDB's current front door returns
    -- HTTP 400 for pg_net requests with those headers, while the plain request
    -- is accepted and returns the documented JSON payload.
    v_request_id := net.http_get(
      url := format(
        'https://www.thesportsdb.com/api/v1/json/123/eventsround.php?id=4422&r=%s&s=2026-2027',
        v_round
      ),
      timeout_milliseconds := 20000
    );

    insert into public.sporting_round_fetch_requests(request_id,league_id,season,round_number)
    values(v_request_id,'4422','2026-2027',v_round)
    on conflict (request_id) do nothing;
    v_count := v_count + 1;
  end loop;

  return v_count;
end;
$$;

revoke all on function public.enqueue_thesportsdb_rounds_v1() from public, anon, authenticated;
grant execute on function public.enqueue_thesportsdb_rounds_v1() to service_role;

create or replace function public.refresh_thesportsdb_stakes_shadow_v1()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_max_round integer;
  v_missing_rounds integer;
  v_inserted integer := 0;
begin
  select max(round_number) into v_max_round
  from public.sporting_league_matches_shadow
  where league_id='4422' and season='2026-2027' and completed=true;

  if v_max_round is null then return 0; end if;

  with coverage as (
    select round_number,count(*) as fixtures
    from public.sporting_league_matches_shadow
    where league_id='4422'
      and season='2026-2027'
      and round_number between 1 and v_max_round
    group by round_number
  )
  select count(*) into v_missing_rounds
  from generate_series(1,v_max_round) r
  left join coverage c on c.round_number=r
  where coalesce(c.fixtures,0) < 9;

  -- Fail closed if any historical round is incomplete in our source cache.
  if v_missing_rounds > 0 then return 0; end if;

  with match_rows as (
    select sporting_canonical_team_v1(home_team) team_key,
           home_team team_name,
           1 played,
           case when home_score>away_score then 1 else 0 end wins,
           case when home_score=away_score then 1 else 0 end draws,
           case when home_score<away_score then 1 else 0 end losses,
           home_score goals_for,
           away_score goals_against,
           case when home_score>away_score then 3 when home_score=away_score then 1 else 0 end points
    from public.sporting_league_matches_shadow
    where league_id='4422' and season='2026-2027' and completed=true

    union all

    select sporting_canonical_team_v1(away_team),
           away_team,
           1,
           case when away_score>home_score then 1 else 0 end,
           case when away_score=home_score then 1 else 0 end,
           case when away_score<home_score then 1 else 0 end,
           away_score,
           home_score,
           case when away_score>home_score then 3 when away_score=home_score then 1 else 0 end
    from public.sporting_league_matches_shadow
    where league_id='4422' and season='2026-2027' and completed=true
  ), team_stats as (
    select team_key,
           max(team_name) team_name,
           sum(played)::int played,
           sum(wins)::int wins,
           sum(draws)::int draws,
           sum(losses)::int losses,
           sum(goals_for)::int goals_for,
           sum(goals_against)::int goals_against,
           (sum(goals_for)-sum(goals_against))::int goal_difference,
           sum(points)::int points
    from match_rows
    group by team_key
  ), ranked as (
    select *,
           row_number() over(
             order by points desc,goal_difference desc,goals_for desc,team_key
           )::int rank,
           count(*) over(partition by points)::int same_points_count
    from team_stats
  ), candidate as (
    select e.id ticket_event_id,
           e.home_team,
           e.away_team,
           h.rank home_rank,
           a.rank away_rank,
           h.points home_points,
           a.points away_points,
           h.played home_played,
           a.played away_played,
           h.goal_difference home_gd,
           a.goal_difference away_gd,
           (h.same_points_count>1 or a.same_points_count>1) tie_ambiguous,
           ((h.played+a.played)/2.0)/34.0 progress,
           case
             when h.rank<=2 then 15.0
             when h.rank<=4 then 12.0
             when h.rank>=16 then 15.0
             when h.rank<=6 or h.rank>=14 then 6.0
             else 3.0
           end home_zone_component,
           ref.numeric_value manual_reference,
           ref.source_name manual_source,
           ref.observed_at manual_observed_at
    from public.ticket_events e
    join ranked h on h.team_key=public.sporting_canonical_team_v1(e.home_team)
    join ranked a on a.team_key=public.sporting_canonical_team_v1(e.away_team)
    left join lateral (
      select numeric_value,source_name,observed_at
      from public.event_context_observations o
      where o.ticket_event_id=e.id
        and o.feature_key='sport.match_stakes'
        and o.numeric_value is not null
      order by observed_at desc
      limit 1
    ) ref on true
    where e.kickoff_at>=now()
      and e.kickoff_at<now()+interval '30 days'
      and e.competition ilike '%Ekstraklasa%'
  ), scored as (
    select *,
      round(least(100.0,greatest(0.0,
        20.0
        + 25.0*least(greatest(progress,0.0),1.0)
        + home_zone_component
        + case
            when abs(home_points-away_points)<=3 and abs(home_rank-away_rank)<=3 then 10.0
            when abs(home_points-away_points)<=6 and abs(home_rank-away_rank)<=5 then 5.0
            else 0.0
          end
        + case
            when progress>=0.75 and home_zone_component>=12.0
              then 15.0*((progress-0.75)/0.25)
            else 0.0
          end
      )),1) stakes_score
    from candidate
  )
  insert into public.sporting_context_shadow_samples(
    ticket_event_id,feature_key,observed_at,numeric_value,text_value,confidence,
    source_name,source_snapshot_key,validation_status,
    manual_reference_numeric,delta_numeric,metadata
  )
  select ticket_event_id,
         'sport.match_stakes',
         now(),
         stakes_score,
         format(
           '%s: %s. miejsce, %s pkt/%s; %s: %s. miejsce, %s pkt/%s',
           home_team,home_rank,home_points,home_played,
           away_team,away_rank,away_points,away_played
         ),
         case when tie_ambiguous then 0.6800 else 0.7600 end,
         'TheSportsDB v1 shadow',
         format(
           'thesportsdb:stakes:v01:%s:r%s:%s',
           ticket_event_id,v_max_round,to_char(now() at time zone 'UTC','YYYYMMDD"T"HH24MI')
         ),
         case
           when manual_reference is null then 'no_reference'
           when abs(stakes_score-manual_reference)<=0.1 then 'matched_reference'
           else 'different_from_reference'
         end,
         manual_reference,
         case when manual_reference is null then null else round(stakes_score-manual_reference,4) end,
         jsonb_build_object(
           'league_id','4422',
           'season','2026-2027',
           'max_completed_round',v_max_round,
           'home_rank',home_rank,
           'away_rank',away_rank,
           'home_points',home_points,
           'away_points',away_points,
           'home_played',home_played,
           'away_played',away_played,
           'home_goal_difference',home_gd,
           'away_goal_difference',away_gd,
           'rank_method','points_goal_difference_goals_for_shadow',
           'tie_break_ambiguous',tie_ambiguous,
           'manual_reference_source',manual_source,
           'manual_reference_observed_at',manual_observed_at,
           'source_tier','free_v1_shadow_not_canonical',
           'scoring_status','research_heuristic_not_model_active',
           'production_impact','none_shadow_only'
         )
  from scored
  on conflict (ticket_event_id,feature_key,source_name,source_snapshot_key)
  do update set
    numeric_value=excluded.numeric_value,
    text_value=excluded.text_value,
    confidence=excluded.confidence,
    validation_status=excluded.validation_status,
    manual_reference_numeric=excluded.manual_reference_numeric,
    delta_numeric=excluded.delta_numeric,
    metadata=excluded.metadata;

  get diagnostics v_inserted = row_count;
  return v_inserted;
end;
$$;

revoke all on function public.refresh_thesportsdb_stakes_shadow_v1() from public, anon, authenticated;
grant execute on function public.refresh_thesportsdb_stakes_shadow_v1() to service_role;

create or replace function public.process_thesportsdb_round_responses_v1()
returns integer
language plpgsql
security invoker
set search_path=public,net,pg_temp
as $$
declare
  r record;
  ev jsonb;
  v_processed integer := 0;
begin
  for r in
    select q.request_id,q.round_number,h.status_code,h.content,h.timed_out,h.error_msg
    from public.sporting_round_fetch_requests q
    join net._http_response h on h.id=q.request_id
    where q.status='queued'
    order by q.requested_at
  loop
    if r.status_code<>200 or coalesce(r.timed_out,false) or r.error_msg is not null then
      update public.sporting_round_fetch_requests
      set status='error',
          processed_at=now(),
          error_text=coalesce(r.error_msg,format('HTTP %s',r.status_code))
      where request_id=r.request_id;
      continue;
    end if;

    begin
      for ev in select value from jsonb_array_elements((r.content::jsonb)->'events')
      loop
        insert into public.sporting_league_matches_shadow(
          source_event_id,league_id,season,round_number,event_date,
          home_team,away_team,home_score,away_score,match_status,completed,
          fetched_at,metadata
        ) values (
          ev->>'idEvent',
          '4422',
          '2026-2027',
          coalesce(nullif(ev->>'intRound','')::int,r.round_number),
          nullif(ev->>'dateEvent','')::date,
          ev->>'strHomeTeam',
          ev->>'strAwayTeam',
          nullif(ev->>'intHomeScore','')::int,
          nullif(ev->>'intAwayScore','')::int,
          ev->>'strStatus',
          (ev->>'strStatus'='FT'),
          now(),
          jsonb_build_object(
            'id_api_football',ev->>'idAPIfootball',
            'postponed',ev->>'strPostponed',
            'locked',ev->>'strLocked'
          )
        )
        on conflict (source_event_id) do update set
          round_number=excluded.round_number,
          event_date=excluded.event_date,
          home_team=excluded.home_team,
          away_team=excluded.away_team,
          home_score=excluded.home_score,
          away_score=excluded.away_score,
          match_status=excluded.match_status,
          completed=excluded.completed,
          fetched_at=excluded.fetched_at,
          metadata=excluded.metadata;
      end loop;

      update public.sporting_round_fetch_requests
      set status='processed',processed_at=now(),error_text=null
      where request_id=r.request_id;
      v_processed := v_processed + 1;
    exception when others then
      update public.sporting_round_fetch_requests
      set status='error',processed_at=now(),error_text=sqlerrm
      where request_id=r.request_id;
    end;
  end loop;

  perform public.refresh_thesportsdb_stakes_shadow_v1();
  return v_processed;
end;
$$;

revoke all on function public.process_thesportsdb_round_responses_v1() from public, anon, authenticated;
grant execute on function public.process_thesportsdb_round_responses_v1() to service_role;

