begin
  select jobid into v_job from cron.job where jobname='thesportsdb_stakes_enqueue_6h';
  if v_job is not null then perform cron.unschedule(v_job); end if;
  select jobid into v_job from cron.job where jobname='thesportsdb_stakes_process_5m';
  if v_job is not null then perform cron.unschedule(v_job); end if;
end $$;

select cron.schedule(
  'thesportsdb_stakes_enqueue_6h',
  '5 */6 * * *',
  $$select public.enqueue_thesportsdb_rounds_v1();$$
);

