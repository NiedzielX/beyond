-- Beyond Ticketing — TheSportsDB Ekstraklasa Match Stakes shadow v2.
--
-- Architecture:
--   pg_cron -> pg_net -> TheSportsDB round endpoints -> raw fixture cache
--   -> reconstructed standings -> league_match_stakes_v01-equivalent SQL score
--   -> comparison with latest verified sport.match_stakes reference.
--
-- Research/shadow only. This pipeline MUST NOT update event_context_observations
-- and MUST NOT modify production P10/P50/P90.
-- A match counts in the table ONLY when TheSportsDB strStatus = 'FT'.

create table if not exists public.sporting_context_shadow_samples (
  id bigint generated by default as identity primary key,
  ticket_event_id bigint not null references public.ticket_events(id) on delete cascade,
  feature_key text not null,
  observed_at timestamptz not null,
  numeric_value numeric,
  text_value text,
  confidence numeric(5,4) not null default 0.7000 check (confidence >= 0 and confidence <= 1),
  source_name text not null,
  source_snapshot_key text not null,
  validation_status text not null default 'no_reference'
    check (validation_status in ('no_reference','matched_reference','different_from_reference')),
  manual_reference_numeric numeric,
  delta_numeric numeric,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(ticket_event_id, feature_key, source_name, source_snapshot_key)
);

create index if not exists idx_sporting_context_shadow_event_feature_time
  on public.sporting_context_shadow_samples(ticket_event_id, feature_key, observed_at desc);
create index if not exists idx_sporting_context_shadow_validation
  on public.sporting_context_shadow_samples(validation_status, observed_at desc);

alter table public.sporting_context_shadow_samples enable row level security;
revoke all on public.sporting_context_shadow_samples from anon, authenticated;
grant select, insert, update, delete on public.sporting_context_shadow_samples to service_role;
grant usage, select on sequence public.sporting_context_shadow_samples_id_seq to service_role;

