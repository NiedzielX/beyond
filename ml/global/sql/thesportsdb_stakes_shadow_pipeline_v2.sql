create view public.dashboard_sporting_shadow_v1
with (security_invoker = true)
as
select distinct on (s.ticket_event_id, s.feature_key)
  s.ticket_event_id,
  e.home_team,
  e.away_team,
  e.kickoff_at,
  s.feature_key,
  s.observed_at,
  s.numeric_value,
  s.text_value,
  s.confidence,
  s.source_name,
  s.validation_status,
  s.manual_reference_numeric,
  s.delta_numeric
from public.sporting_context_shadow_samples s
join public.ticket_events e on e.id=s.ticket_event_id
where s.feature_key='sport.match_stakes'
order by s.ticket_event_id,s.feature_key,s.observed_at desc;

revoke all on public.dashboard_sporting_shadow_v1 from public;
grant select on public.dashboard_sporting_shadow_v1 to anon, authenticated, service_role;

create view public.dashboard_sporting_shadow_summary_v1
with (security_invoker = true)
as
select
  count(*)::int as total_events,
  count(*) filter (where validation_status='matched_reference')::int as matched_reference,
  count(*) filter (where validation_status='different_from_reference')::int as different_reference,
  count(*) filter (where validation_status='no_reference')::int as no_reference,
  round(avg(abs(delta_numeric)) filter (where delta_numeric is not null),3) as mean_abs_delta,
  max(observed_at) as latest_observed_at
from public.dashboard_sporting_shadow_v1;

revoke all on public.dashboard_sporting_shadow_summary_v1 from public;
grant select on public.dashboard_sporting_shadow_summary_v1 to anon, authenticated, service_role;

