-- Beyond Ticketing — cross-club checkpoint baseline v3.
--
-- Research fallback only. It never replaces an existing incumbent historical P50.
-- A fallback baseline is available only for home Ekstraklasa events with >=3
-- verified prior home attendance outcomes strictly before the snapshot checkpoint.

create table if not exists public.crossclub_checkpoint_baselines_v3 (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.event_context_snapshots_v1(id) on delete cascade,
  ticket_event_id bigint not null references public.ticket_events(id) on delete cascade,
  checkpoint_code text not null references public.context_checkpoint_definitions(checkpoint_code),
  checkpoint_at timestamptz not null,
  club_slug text not null,
  competition_key text not null,
  history_count integer not null,
  history_first_at timestamptz,
  history_last_at timestamptz,
  baseline_mean numeric,
  baseline_p50 integer,
  baseline_model text not null default 'club_trailing_home_median_v3',
  baseline_status text not null check (baseline_status in ('ready','insufficient_history','unsupported_competition')),
  evaluation_mode text not null check (evaluation_mode in ('prospective','retrospective_point_in_time')),
  source_cutoff_at timestamptz not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(snapshot_id)
);

create index if not exists idx_crossclub_checkpoint_baselines_event_checkpoint
  on public.crossclub_checkpoint_baselines_v3(ticket_event_id,checkpoint_at);
create index if not exists idx_crossclub_checkpoint_baselines_status
  on public.crossclub_checkpoint_baselines_v3(baseline_status,checkpoint_code);

alter table public.crossclub_checkpoint_baselines_v3 enable row level security;
revoke all on public.crossclub_checkpoint_baselines_v3 from anon,authenticated;
grant select,insert,update,delete on public.crossclub_checkpoint_baselines_v3 to service_role;
grant usage,select on sequence public.crossclub_checkpoint_baselines_v3_id_seq to service_role;

create or replace function public.refresh_crossclub_checkpoint_baselines_v3()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_rows integer := 0;
begin
  with computed as (
    select
      s.id as snapshot_id,
      s.ticket_event_id,
      s.checkpoint_code,
      s.checkpoint_at,
      s.capture_mode,
      e.club_slug,
      public.match_competition_key_v1(e.competition) as competition_key,
      count(h.*)::int as history_count,
      min(h.kickoff_at) as history_first_at,
      max(h.kickoff_at) as history_last_at,
      avg(h.actual_attendance)::numeric as baseline_mean,
      percentile_cont(0.5) within group (order by h.actual_attendance)::numeric as baseline_median,
      case
        when public.match_competition_key_v1(e.competition) <> 'ekstraklasa' then 'unsupported_competition'
        when count(h.*) < 3 then 'insufficient_history'
        else 'ready'
      end as baseline_status
    from public.event_context_snapshots_v1 s
    join public.ticket_events e on e.id=s.ticket_event_id
    left join public.ml_home_attendance_history_v2 h
      on h.club_slug=e.club_slug
     and h.competition_key='ekstraklasa'
     and h.kickoff_at<s.checkpoint_at
    group by s.id,s.ticket_event_id,s.checkpoint_code,s.checkpoint_at,s.capture_mode,
             e.club_slug,e.competition
  )
  insert into public.crossclub_checkpoint_baselines_v3(
    snapshot_id,ticket_event_id,checkpoint_code,checkpoint_at,club_slug,competition_key,
    history_count,history_first_at,history_last_at,baseline_mean,baseline_p50,
    baseline_model,baseline_status,evaluation_mode,source_cutoff_at,metadata
  )
  select
    c.snapshot_id,c.ticket_event_id,c.checkpoint_code,c.checkpoint_at,c.club_slug,c.competition_key,
    c.history_count,c.history_first_at,c.history_last_at,c.baseline_mean,
    case when c.baseline_status='ready' then round(c.baseline_median)::int else null end,
    'club_trailing_home_median_v3',c.baseline_status,c.capture_mode,c.checkpoint_at,
    jsonb_build_object(
      'minimum_history_count',3,
      'competition_scope','ekstraklasa_home_only',
      'statistic','median_verified_home_attendance',
      'history_rule','verified home attendance strictly before checkpoint_at',
      'production_impact','none_research_baseline_only'
    )
  from computed c
  on conflict (snapshot_id) do nothing;

  get diagnostics v_rows=row_count;

  insert into public.context_ablation_predictions_v1(
    snapshot_id,variant_key,predicted_p50,prediction_method,model_version,metadata
  )
  select
    b.snapshot_id,
    'baseline',
    b.baseline_p50,
    'crossclub_checkpoint_baseline_fallback',
    b.baseline_model,
    jsonb_build_object(
      'crossclub_baseline_id',b.id,
      'history_count',b.history_count,
      'history_first_at',b.history_first_at,
      'history_last_at',b.history_last_at,
      'source_cutoff_at',b.source_cutoff_at,
      'evaluation_mode',b.evaluation_mode,
      'fallback_only',true
    )
  from public.crossclub_checkpoint_baselines_v3 b
  left join public.context_ablation_predictions_v1 existing
    on existing.snapshot_id=b.snapshot_id
   and existing.variant_key='baseline'
  where b.baseline_status='ready'
    and b.baseline_p50 is not null
    and existing.id is null
  on conflict (snapshot_id,variant_key) do nothing;

  return v_rows;
end;
$$;

revoke all on function public.refresh_crossclub_checkpoint_baselines_v3() from public,anon,authenticated;
grant execute on function public.refresh_crossclub_checkpoint_baselines_v3() to service_role;

drop view if exists public.dashboard_crossclub_baseline_v3;
create view public.dashboard_crossclub_baseline_v3
with (security_invoker=true)
as
select
  b.snapshot_id,
  b.ticket_event_id,
  e.home_team,
  e.away_team,
  e.kickoff_at,
  b.checkpoint_code,
  b.checkpoint_at,
  b.club_slug,
  b.history_count,
  b.history_first_at,
  b.history_last_at,
  b.baseline_p50,
  b.baseline_status,
  b.baseline_model,
  b.evaluation_mode,
  case
    when p.prediction_method='snapshot_historical_baseline' then 'incumbent_engine_baseline'
    when p.prediction_method='crossclub_checkpoint_baseline_fallback' then 'crossclub_fallback'
    else 'no_baseline_prediction'
  end as selected_baseline_source,
  p.predicted_p50 as selected_baseline_p50,
  (o.actual_attendance is not null) as has_outcome
from public.crossclub_checkpoint_baselines_v3 b
join public.ticket_events e on e.id=b.ticket_event_id
left join public.context_ablation_predictions_v1 p
  on p.snapshot_id=b.snapshot_id and p.variant_key='baseline'
left join public.ticket_event_outcomes o on o.ticket_event_id=b.ticket_event_id;

revoke all on public.dashboard_crossclub_baseline_v3 from public;

create or replace view public.dashboard_context_snapshot_readiness_v1
with (security_invoker=true)
as
with due as (
  select c.checkpoint_code,c.sort_order,count(*)::int as due_event_count
  from public.ticket_events e
  cross join public.context_checkpoint_definitions c
  where c.is_active
    and e.kickoff_at>=now()-interval '120 days'
    and e.kickoff_at<now()+interval '180 days'
    and e.kickoff_at-make_interval(hours=>c.hours_before_kickoff)<=now()
  group by c.checkpoint_code,c.sort_order
), captured as (
  select
    s.checkpoint_code,
    count(*)::int as captured_count,
    count(*) filter (where s.capture_mode='prospective')::int as prospective_count,
    count(*) filter (where bp.id is not null)::int as baseline_ready_count,
    count(*) filter (where o.actual_attendance is not null)::int as outcome_paired_count,
    round(avg(s.context_observed_count::numeric/nullif(s.context_total_count,0))*100.0,1) as avg_context_coverage_pct
  from public.event_context_snapshots_v1 s
  left join public.context_ablation_predictions_v1 bp
    on bp.snapshot_id=s.id and bp.variant_key='baseline'
  left join public.ticket_event_outcomes o on o.ticket_event_id=s.ticket_event_id
  group by s.checkpoint_code
)
select
  d.checkpoint_code,d.sort_order,d.due_event_count,
  coalesce(c.captured_count,0) as captured_count,
  coalesce(c.prospective_count,0) as prospective_count,
  coalesce(c.baseline_ready_count,0) as baseline_ready_count,
  coalesce(c.outcome_paired_count,0) as outcome_paired_count,
  c.avg_context_coverage_pct
from due d
left join captured c on c.checkpoint_code=d.checkpoint_code
order by d.sort_order;

revoke all on public.dashboard_context_snapshot_readiness_v1 from public;
grant select on public.dashboard_context_snapshot_readiness_v1 to anon,authenticated,service_role;

