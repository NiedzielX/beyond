-- Beyond Ticketing — Event Context Snapshot & Ablation v1.
--
-- Purpose:
-- 1. Freeze point-in-time context at T-7d / T-3d / T-24h / T-6h.
-- 2. Prevent leakage by accepting only context known and persisted before the checkpoint.
-- 3. Store only real forecast variants. No weighted 45/30/15/10 pseudo-forecast is generated.
-- 4. Evaluate every variant against baseline on the exact same completed-event sample.

create table if not exists public.context_checkpoint_definitions (
  checkpoint_code text primary key,
  hours_before_kickoff integer not null check (hours_before_kickoff > 0),
  sort_order integer not null unique,
  is_active boolean not null default true,
  description text not null
);

insert into public.context_checkpoint_definitions(checkpoint_code,hours_before_kickoff,sort_order,description)
values
  ('T-7d',168,1,'Seven days before kickoff'),
  ('T-3d',72,2,'Three days before kickoff'),
  ('T-24h',24,3,'Twenty-four hours before kickoff'),
  ('T-6h',6,4,'Six hours before kickoff')
on conflict (checkpoint_code) do update set
  hours_before_kickoff=excluded.hours_before_kickoff,
  sort_order=excluded.sort_order,
  is_active=true,
  description=excluded.description;

alter table public.context_checkpoint_definitions enable row level security;
revoke all on public.context_checkpoint_definitions from anon,authenticated;
grant select,insert,update,delete on public.context_checkpoint_definitions to service_role;

create table if not exists public.event_context_snapshots_v1 (
  id bigint generated by default as identity primary key,
  ticket_event_id bigint not null references public.ticket_events(id) on delete cascade,
  checkpoint_code text not null references public.context_checkpoint_definitions(checkpoint_code),
  checkpoint_at timestamptz not null,
  captured_at timestamptz not null default now(),
  capture_mode text not null check (capture_mode in ('prospective','retrospective_point_in_time')),
  baseline_forecast_id bigint references public.forecast_observations(id) on delete set null,
  baseline_forecast_generated_at timestamptz,
  baseline_model_version text,
  baseline_historical_model text,
  baseline_historical_p50 integer,
  engine_final_p50 integer,
  engine_correction_status text,
  engine_signal_readiness text,
  ticketing_payload jsonb not null default '{}'::jsonb,
  context_features jsonb not null default '{}'::jsonb,
  context_observed_count integer not null default 0,
  context_total_count integer not null default 0,
  blocked_feature_count integer not null default 0,
  degraded_feature_count integer not null default 0,
  snapshot_status text not null check (snapshot_status in ('captured','captured_without_baseline')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(ticket_event_id,checkpoint_code)
);

create index if not exists idx_event_context_snapshots_checkpoint
  on public.event_context_snapshots_v1(checkpoint_code,checkpoint_at);
create index if not exists idx_event_context_snapshots_event
  on public.event_context_snapshots_v1(ticket_event_id,checkpoint_at);
create index if not exists idx_event_context_snapshots_baseline_forecast
  on public.event_context_snapshots_v1(baseline_forecast_id);

alter table public.event_context_snapshots_v1 enable row level security;
revoke all on public.event_context_snapshots_v1 from anon,authenticated;
grant select,insert,update,delete on public.event_context_snapshots_v1 to service_role;
grant usage,select on sequence public.event_context_snapshots_v1_id_seq to service_role;

create table if not exists public.context_ablation_variants_v1 (
  variant_key text primary key,
  sort_order integer not null unique,
  display_name text not null,
  description text not null,
  is_active boolean not null default true
);

insert into public.context_ablation_variants_v1(variant_key,sort_order,display_name,description)
values
  ('baseline',1,'Baseline','Historical attendance baseline only.'),
  ('baseline_ticketing',2,'Baseline + Ticketing','Historical baseline with an empirically active live-ticketing adjustment.'),
  ('baseline_ticketing_sporting',3,'+ Sporting','Ticketing variant plus Sporting Context.'),
  ('baseline_ticketing_sporting_match',4,'+ Match Context','Sporting variant plus Match Context.'),
  ('baseline_ticketing_sporting_match_hype',5,'+ Attention & Hype','Match-context variant plus Attention & Hype.')
on conflict (variant_key) do update set
  sort_order=excluded.sort_order,
  display_name=excluded.display_name,
  description=excluded.description,
  is_active=true;

alter table public.context_ablation_variants_v1 enable row level security;
revoke all on public.context_ablation_variants_v1 from anon,authenticated;
grant select,insert,update,delete on public.context_ablation_variants_v1 to service_role;

create table if not exists public.context_ablation_predictions_v1 (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.event_context_snapshots_v1(id) on delete cascade,
  variant_key text not null references public.context_ablation_variants_v1(variant_key),
  predicted_p50 integer not null check (predicted_p50 >= 0),
  prediction_method text not null,
  model_version text,
  generated_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique(snapshot_id,variant_key)
);

create index if not exists idx_context_ablation_predictions_variant
  on public.context_ablation_predictions_v1(variant_key,snapshot_id);

alter table public.context_ablation_predictions_v1 enable row level security;
revoke all on public.context_ablation_predictions_v1 from anon,authenticated;
grant select,insert,update,delete on public.context_ablation_predictions_v1 to service_role;
grant usage,select on sequence public.context_ablation_predictions_v1_id_seq to service_role;

create or replace function public.capture_due_event_context_snapshots_v1()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  v_inserted integer := 0;
begin
  with due as (
    select e.id ticket_event_id,e.club_slug,e.home_team,e.away_team,e.competition,e.kickoff_at,
      c.checkpoint_code,c.hours_before_kickoff,
      e.kickoff_at-make_interval(hours=>c.hours_before_kickoff) checkpoint_at
    from public.ticket_events e
    cross join public.context_checkpoint_definitions c
    where c.is_active
      and e.kickoff_at>=now()-interval '120 days'
      and e.kickoff_at<now()+interval '180 days'
      and e.kickoff_at-make_interval(hours=>c.hours_before_kickoff)<=now()
  ), prepared as (
    select d.*,
      f.id baseline_forecast_id,f.forecast_generated_at,f.model_version,f.historical_model,
      f.historical_p50,f.final_p50,f.correction_status,f.signal_readiness,
      f.source_snapshot_id,f.source_snapshot_captured_at,
      f.live_available_total,f.live_first_available_total,f.live_available_index,
      f.live_net_removed_since_first,f.live_net_removed_since_previous,
      f.live_velocity_since_previous,f.live_net_removed_6h,f.live_velocity_6h,
      f.live_net_removed_24h,f.live_velocity_24h,f.live_acceleration_6h_vs_24h,
      f.live_raw_snapshot_count,f.live_clean_snapshot_count,f.live_excluded_anomaly_count,
      pack.context_features,pack.context_observed_count,pack.context_total_count,
      pack.blocked_feature_count,pack.degraded_feature_count
    from due d
    left join lateral (
      select fo.*
      from public.forecast_observations fo
      where fo.ticket_event_id=d.ticket_event_id
        and fo.forecast_generated_at<=d.checkpoint_at
        and (fo.source_snapshot_captured_at is null or fo.source_snapshot_captured_at<=d.checkpoint_at)
        and (fo.historical_p50 is not null or fo.final_p50 is not null)
      order by fo.forecast_generated_at desc,fo.id desc
      limit 1
    ) f on true
    cross join lateral (
      select
        coalesce(jsonb_object_agg(x.feature_key,x.feature_value order by x.feature_key),'{}'::jsonb) context_features,
        count(*) filter (where x.status='observed')::int context_observed_count,
        count(*)::int context_total_count,
        count(*) filter (where x.status='blocked_external_access')::int blocked_feature_count,
        count(*) filter (where x.status='degraded_automation')::int degraded_feature_count
      from (
        select fd.feature_key,
          case when o.id is not null then 'observed'
               when fd.collection_status='blocked_external_access' then 'blocked_external_access'
               when fd.collection_status='degraded_automation' then 'degraded_automation'
               else 'unknown' end status,
          jsonb_build_object(
            'status',case when o.id is not null then 'observed'
              when fd.collection_status='blocked_external_access' then 'blocked_external_access'
              when fd.collection_status='degraded_automation' then 'degraded_automation'
              else 'unknown' end,
            'group_key',fd.group_key,'numeric_value',o.numeric_value,
            'boolean_value',o.boolean_value,'text_value',o.text_value,
            'normalized_score',o.normalized_score,'confidence',o.confidence,
            'source_name',o.source_name,'observed_at',o.observed_at,
            'source_observed_at',o.source_observed_at,'source_record_key',o.source_record_key
          ) feature_value
        from public.context_feature_definitions fd
        left join lateral (
          select eo.*
          from public.event_context_observations eo
          where eo.ticket_event_id=d.ticket_event_id
            and eo.feature_key=fd.feature_key
            and eo.observed_at<=d.checkpoint_at
            and eo.created_at<=d.checkpoint_at
            and coalesce(eo.source_observed_at,eo.observed_at)<=d.checkpoint_at
          order by eo.observed_at desc,eo.id desc
          limit 1
        ) o on true
        where fd.is_active and fd.group_key<>'ticketing'
      ) x
    ) pack
  )
  insert into public.event_context_snapshots_v1(
    ticket_event_id,checkpoint_code,checkpoint_at,captured_at,capture_mode,
    baseline_forecast_id,baseline_forecast_generated_at,baseline_model_version,
    baseline_historical_model,baseline_historical_p50,engine_final_p50,
    engine_correction_status,engine_signal_readiness,ticketing_payload,context_features,
    context_observed_count,context_total_count,blocked_feature_count,degraded_feature_count,
    snapshot_status,metadata
  )
  select p.ticket_event_id,p.checkpoint_code,p.checkpoint_at,now(),
    case when now()<=p.checkpoint_at+interval '30 minutes' then 'prospective' else 'retrospective_point_in_time' end,
    p.baseline_forecast_id,p.forecast_generated_at,p.model_version,p.historical_model,
    p.historical_p50,p.final_p50,p.correction_status,p.signal_readiness,
    jsonb_build_object(
      'source_snapshot_id',p.source_snapshot_id,
      'source_snapshot_captured_at',p.source_snapshot_captured_at,
      'available_total',p.live_available_total,
      'first_available_total',p.live_first_available_total,
      'trajectory_position_available_index',p.live_available_index,
      'net_removed_since_first',p.live_net_removed_since_first,
      'net_removed_since_previous',p.live_net_removed_since_previous,
      'velocity_since_previous',p.live_velocity_since_previous,
      'net_removed_6h',p.live_net_removed_6h,'velocity_6h',p.live_velocity_6h,
      'net_removed_24h',p.live_net_removed_24h,'velocity_24h',p.live_velocity_24h,
      'acceleration_6h_vs_24h',p.live_acceleration_6h_vs_24h,
      'raw_snapshot_count',p.live_raw_snapshot_count,'clean_snapshot_count',p.live_clean_snapshot_count,
      'excluded_anomaly_count',p.live_excluded_anomaly_count,
      'scarcity_note','Raw available_total is frozen; no new scarcity transformation is invented by snapshot v1.',
      'signal_readiness',p.signal_readiness
    ),
    p.context_features,p.context_observed_count,p.context_total_count,
    p.blocked_feature_count,p.degraded_feature_count,
    case when p.historical_p50 is null then 'captured_without_baseline' else 'captured' end,
    jsonb_build_object(
      'home_team',p.home_team,'away_team',p.away_team,'competition',p.competition,
      'club_slug',p.club_slug,'kickoff_at',p.kickoff_at,'data_cutoff_at',p.checkpoint_at,
      'leakage_rule','event context requires observed_at, created_at and source_observed_at <= checkpoint; forecast requires generated_at and source snapshot <= checkpoint',
      'immutability','snapshot row is insert-only after first capture'
    )
  from prepared p
  on conflict (ticket_event_id,checkpoint_code) do nothing;

  get diagnostics v_inserted=row_count;

  insert into public.context_ablation_predictions_v1(snapshot_id,variant_key,predicted_p50,prediction_method,model_version,metadata)
  select s.id,'baseline',s.baseline_historical_p50,'snapshot_historical_baseline',s.baseline_historical_model,
    jsonb_build_object('source_forecast_id',s.baseline_forecast_id,'checkpoint_code',s.checkpoint_code)
  from public.event_context_snapshots_v1 s
  where s.baseline_historical_p50 is not null
  on conflict (snapshot_id,variant_key) do nothing;

  insert into public.context_ablation_predictions_v1(snapshot_id,variant_key,predicted_p50,prediction_method,model_version,metadata)
  select s.id,'baseline_ticketing',s.engine_final_p50,'existing_controlled_live_blend',s.baseline_model_version,
    jsonb_build_object('source_forecast_id',s.baseline_forecast_id,'correction_status',s.engine_correction_status,
      'signal_readiness',s.engine_signal_readiness,'checkpoint_code',s.checkpoint_code)
  from public.event_context_snapshots_v1 s
  where s.engine_final_p50 is not null
    and s.baseline_historical_p50 is not null
    and s.engine_final_p50<>s.baseline_historical_p50
    and s.engine_correction_status like 'controlled_live_blend%'
  on conflict (snapshot_id,variant_key) do nothing;

  return v_inserted;
end;
$$;

revoke all on function public.capture_due_event_context_snapshots_v1() from public,anon,authenticated;
grant execute on function public.capture_due_event_context_snapshots_v1() to service_role;

drop view if exists public.dashboard_context_snapshot_readiness_v1;
create view public.dashboard_context_snapshot_readiness_v1
with (security_invoker=true)
as
with due as (
  select c.checkpoint_code,c.sort_order,count(*)::int due_event_count
  from public.ticket_events e
  cross join public.context_checkpoint_definitions c
  where c.is_active
    and e.kickoff_at>=now()-interval '120 days'
    and e.kickoff_at<now()+interval '180 days'
    and e.kickoff_at-make_interval(hours=>c.hours_before_kickoff)<=now()
  group by c.checkpoint_code,c.sort_order
), captured as (
  select s.checkpoint_code,count(*)::int captured_count,
    count(*) filter (where s.capture_mode='prospective')::int prospective_count,
    count(*) filter (where s.baseline_historical_p50 is not null)::int baseline_ready_count,
    count(*) filter (where o.actual_attendance is not null)::int outcome_paired_count,
    round(avg(s.context_observed_count::numeric/nullif(s.context_total_count,0))*100.0,1) avg_context_coverage_pct
  from public.event_context_snapshots_v1 s
  left join public.ticket_event_outcomes o on o.ticket_event_id=s.ticket_event_id
  group by s.checkpoint_code
)
select d.checkpoint_code,d.sort_order,d.due_event_count,
  coalesce(c.captured_count,0) captured_count,
  coalesce(c.prospective_count,0) prospective_count,
  coalesce(c.baseline_ready_count,0) baseline_ready_count,
  coalesce(c.outcome_paired_count,0) outcome_paired_count,
  c.avg_context_coverage_pct
from due d left join captured c on c.checkpoint_code=d.checkpoint_code
order by d.sort_order;

revoke all on public.dashboard_context_snapshot_readiness_v1 from public;
grant select on public.dashboard_context_snapshot_readiness_v1 to anon,authenticated,service_role;

drop view if exists public.dashboard_context_ablation_results_v1;
create view public.dashboard_context_ablation_results_v1
with (security_invoker=true)
as
with paired as (
  select s.checkpoint_code,v.variant_key,v.sort_order,v.display_name,s.ticket_event_id,e.club_slug,
    p.predicted_p50 variant_p50,b.predicted_p50 baseline_p50,o.actual_attendance,
    abs(p.predicted_p50-o.actual_attendance)::numeric variant_abs_error,
    abs(b.predicted_p50-o.actual_attendance)::numeric baseline_abs_error,
    (p.predicted_p50-o.actual_attendance)::numeric variant_signed_error,
    (b.predicted_p50-o.actual_attendance)::numeric baseline_signed_error
  from public.event_context_snapshots_v1 s
  join public.ticket_events e on e.id=s.ticket_event_id
  join public.ticket_event_outcomes o on o.ticket_event_id=s.ticket_event_id
  join public.context_ablation_predictions_v1 p on p.snapshot_id=s.id
  join public.context_ablation_predictions_v1 b on b.snapshot_id=s.id and b.variant_key='baseline'
  join public.context_ablation_variants_v1 v on v.variant_key=p.variant_key and v.is_active
  where o.actual_attendance is not null
)
select checkpoint_code,variant_key,sort_order,display_name,
  count(distinct ticket_event_id)::int event_count,count(distinct club_slug)::int club_count,
  round(avg(variant_abs_error),1) variant_mae,
  round(avg(baseline_abs_error),1) baseline_mae_same_events,
  round(avg(baseline_abs_error)-avg(variant_abs_error),1) mae_uplift,
  round(avg(variant_signed_error),1) variant_bias,
  round(avg(baseline_signed_error),1) baseline_bias_same_events
from paired
group by checkpoint_code,variant_key,sort_order,display_name;

revoke all on public.dashboard_context_ablation_results_v1 from public;
grant select on public.dashboard_context_ablation_results_v1 to anon,authenticated,service_role;

drop view if exists public.dashboard_context_ablation_matrix_v1;
create view public.dashboard_context_ablation_matrix_v1
with (security_invoker=true)
as
select c.checkpoint_code,c.sort_order checkpoint_sort_order,
  v.variant_key,v.sort_order variant_sort_order,v.display_name,v.description,
  coalesce(r.event_count,0) event_count,coalesce(r.club_count,0) club_count,
  r.variant_mae,r.baseline_mae_same_events,r.mae_uplift,r.variant_bias,r.baseline_bias_same_events,
  case when coalesce(r.event_count,0)>0 then 'evaluated' else 'no_predictions' end evaluation_status
from public.context_checkpoint_definitions c
cross join public.context_ablation_variants_v1 v
left join public.dashboard_context_ablation_results_v1 r
  on r.checkpoint_code=c.checkpoint_code and r.variant_key=v.variant_key
where c.is_active and v.is_active
order by c.sort_order,v.sort_order;

revoke all on public.dashboard_context_ablation_matrix_v1 from public;
grant select on public.dashboard_context_ablation_matrix_v1 to anon,authenticated,service_role;

