-- Beyond Ticketing — verified rivalry map v1.
--
-- Stores only positively verified rivalry relationships and propagates them to
-- matching fixtures. Missing relation = unknown, never a negative label.
-- Opponent attractiveness is intentionally NOT scored by this map.

create table if not exists public.sporting_rivalry_relations (
  id bigint generated by default as identity primary key,
  team_a text not null,
  team_b text not null,
  team_a_key text not null,
  team_b_key text not null,
  rivalry_type text not null,
  source_name text not null,
  source_url text,
  confidence numeric(5,4) not null default 0.9500 check (confidence >= 0 and confidence <= 1),
  verified_at timestamptz not null,
  is_active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (team_a_key < team_b_key),
  unique(team_a_key, team_b_key)
);

alter table public.sporting_rivalry_relations enable row level security;
revoke all on public.sporting_rivalry_relations from anon, authenticated;
grant select,insert,update,delete on public.sporting_rivalry_relations to service_role;
grant usage,select on sequence public.sporting_rivalry_relations_id_seq to service_role;

