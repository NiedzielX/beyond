create or replace view public.dashboard_model_activation_summary_v1 with (security_invoker=true) as
with approved as (
  select count(*)::int approved_promotion_packages from public.model_promotion_candidate_packages_v1 where review_status='approved_for_promotion'
), contracts as (
  select count(*)::int contract_count,count(*) filter (where contract_status='draft')::int draft_count,
    count(*) filter (where contract_status='ready_for_activation')::int ready_count,
    count(*) filter (where contract_status='activation_approved')::int activation_approved_count,
    count(*) filter (where contract_status in ('paused','rolled_back'))::int stopped_count,
    bool_or(execution_enabled) any_execution_enabled,bool_or(writer_binding_status='production_bound') any_production_binding,
    max(updated_at) latest_contract_update
  from public.model_activation_contracts_v1
)
select a.approved_promotion_packages,c.contract_count,c.draft_count,c.ready_count,c.activation_approved_count,c.stopped_count,
  coalesce(c.any_execution_enabled,false) any_execution_enabled,coalesce(c.any_production_binding,false) any_production_binding,
  c.latest_contract_update,10.0::numeric default_max_abs_adjustment_pct,45::int default_max_input_staleness_minutes,
  5::int default_monitor_window_events,1.05::numeric default_max_mae_ratio_to_champion,3::int default_max_consecutive_worse_outcomes,
  'Contract v1 defines production guardrails but intentionally cannot enable execution or bind the forecast writer.'::text governance_note
from approved a cross join contracts c;
revoke all on public.dashboard_model_activation_summary_v1 from public;
grant select on public.dashboard_model_activation_summary_v1 to anon,authenticated,service_role;

