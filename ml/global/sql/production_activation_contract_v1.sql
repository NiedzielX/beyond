-- Beyond Ticketing — Production Activation Contract v1
-- Control-plane only. Execution remains disabled and no forecast writer is bound.

create table if not exists public.model_activation_contracts_v1 (
  id bigint generated by default as identity primary key,
  promotion_package_id bigint not null unique references public.model_promotion_candidate_packages_v1(id) on delete restrict,
  category_key text not null,
  candidate_key text not null,
  champion_model_key text not null,
  contract_status text not null default 'draft'
    check (contract_status in ('draft','ready_for_activation','activation_approved','paused','rolled_back','retired')),
  activation_mode text not null default 'bounded_overlay' check (activation_mode='bounded_overlay'),
  allowed_horizons text[] not null default array['T-24h']::text[],
  max_abs_adjustment_pct numeric(6,2) not null default 10.0 check (max_abs_adjustment_pct>0 and max_abs_adjustment_pct<=25),
  fail_closed_to_champion boolean not null default true check (fail_closed_to_champion=true),
  max_input_staleness_minutes integer not null default 45 check (max_input_staleness_minutes between 15 and 180),
  kill_switch_enabled boolean not null default true check (kill_switch_enabled=true),
  rollback_mode text not null default 'champion_immediate' check (rollback_mode='champion_immediate'),
  min_post_activation_outcomes integer not null default 5 check (min_post_activation_outcomes>=3),
  rolling_window_events integer not null default 5 check (rolling_window_events>=3),
  max_rolling_mae_ratio_to_champion numeric(6,3) not null default 1.05 check (max_rolling_mae_ratio_to_champion>=1.0),
  max_consecutive_worse_outcomes integer not null default 3 check (max_consecutive_worse_outcomes>=1),
  require_champion_parallel_forecast boolean not null default true check (require_champion_parallel_forecast=true),
  require_audit_payload boolean not null default true check (require_audit_payload=true),
  execution_enabled boolean not null default false check (execution_enabled=false),
  writer_binding_status text not null default 'not_bound' check (writer_binding_status in ('not_bound','shadow_bound','production_bound')),
  created_from_package_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by text,
  review_note text,
  activation_approved_at timestamptz,
  activation_approved_by text,
  activation_note text,
  paused_at timestamptz,
  paused_by text,
  pause_reason text,
  rolled_back_at timestamptz,
  rolled_back_by text,
  rollback_reason text,
  policy_snapshot jsonb not null default '{}'::jsonb
);

create index if not exists idx_model_activation_contracts_status on public.model_activation_contracts_v1(contract_status,created_at desc);
create index if not exists idx_model_activation_contracts_category on public.model_activation_contracts_v1(category_key,created_at desc);
alter table public.model_activation_contracts_v1 enable row level security;
revoke all on public.model_activation_contracts_v1 from anon,authenticated;
grant select (
  id,promotion_package_id,category_key,candidate_key,champion_model_key,contract_status,activation_mode,
  allowed_horizons,max_abs_adjustment_pct,fail_closed_to_champion,max_input_staleness_minutes,
  kill_switch_enabled,rollback_mode,min_post_activation_outcomes,rolling_window_events,
  max_rolling_mae_ratio_to_champion,max_consecutive_worse_outcomes,require_champion_parallel_forecast,
  require_audit_payload,execution_enabled,writer_binding_status,created_from_package_at,created_at,updated_at,
  reviewed_at,reviewed_by,review_note,activation_approved_at,activation_approved_by,activation_note,
  paused_at,paused_by,pause_reason,rolled_back_at,rolled_back_by,rollback_reason
) on public.model_activation_contracts_v1 to anon,authenticated;
grant select,insert,update,delete on public.model_activation_contracts_v1 to service_role;
grant usage,select on sequence public.model_activation_contracts_v1_id_seq to service_role;
create policy dashboard_model_activation_contracts_read on public.model_activation_contracts_v1 for select to anon,authenticated using (true);

