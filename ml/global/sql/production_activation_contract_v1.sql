create table if not exists public.model_activation_health_samples_v1 (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.model_activation_contracts_v1(id) on delete restrict,
  ticket_event_id bigint not null references public.ticket_events(id) on delete restrict,
  observed_at timestamptz not null default now(),
  champion_p50 integer not null,
  challenger_p50 integer not null,
  actual_attendance integer not null,
  champion_abs_error integer generated always as (abs(champion_p50-actual_attendance)) stored,
  challenger_abs_error integer generated always as (abs(challenger_p50-actual_attendance)) stored,
  challenger_worse boolean generated always as (abs(challenger_p50-actual_attendance)>abs(champion_p50-actual_attendance)) stored,
  metadata jsonb not null default '{}'::jsonb,
  unique(contract_id,ticket_event_id)
);
create index if not exists idx_model_activation_health_contract_time on public.model_activation_health_samples_v1(contract_id,observed_at desc);
create index if not exists idx_model_activation_health_ticket_event on public.model_activation_health_samples_v1(ticket_event_id);
alter table public.model_activation_health_samples_v1 enable row level security;
revoke all on public.model_activation_health_samples_v1 from anon,authenticated;
grant select,insert,update,delete on public.model_activation_health_samples_v1 to service_role;
grant usage,select on sequence public.model_activation_health_samples_v1_id_seq to service_role;

create or replace function public.refresh_model_activation_contracts_v1()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare p public.model_promotion_candidate_packages_v1%rowtype; v_champion text; v_id bigint; v_created integer:=0;
begin
  select model_version into v_champion from public.forecast_observations where forecast_status<>'shadow'
  order by forecast_generated_at desc,id desc limit 1;
  v_champion:=coalesce(v_champion,'current-production-p50');
  for p in select * from public.model_promotion_candidate_packages_v1 where review_status='approved_for_promotion' order by reviewed_at nulls last,id loop
    insert into public.model_activation_contracts_v1(
      promotion_package_id,category_key,candidate_key,champion_model_key,contract_status,created_from_package_at,policy_snapshot
    ) values (
      p.id,p.category_key,p.candidate_key,v_champion,'draft',p.frozen_at,
      jsonb_build_object('policy_version','production-activation-contract-v1','allowed_horizons',jsonb_build_array('T-24h'),
        'max_abs_adjustment_pct',10,'fail_closed_to_champion',true,'max_input_staleness_minutes',45,
        'kill_switch_enabled',true,'rollback_mode','champion_immediate','min_post_activation_outcomes',5,
        'rolling_window_events',5,'max_rolling_mae_ratio_to_champion',1.05,'max_consecutive_worse_outcomes',3,
        'require_champion_parallel_forecast',true,'require_audit_payload',true,'execution_enabled',false,'writer_binding_status','not_bound')
    ) on conflict (promotion_package_id) do nothing returning id into v_id;
    if v_id is not null then
      insert into public.model_activation_audit_log_v1(contract_id,action,actor,note,payload)
      values (v_id,'contract_created','system','Created from approved promotion package; execution remains disabled.',jsonb_build_object('promotion_package_id',p.id));
      v_created:=v_created+1;
    end if;
    v_id:=null;
  end loop;
  return v_created;
end;
$$;
revoke all on function public.refresh_model_activation_contracts_v1() from public,anon,authenticated;
grant execute on function public.refresh_model_activation_contracts_v1() to service_role;

create or replace function public.review_model_activation_contract_v1(p_contract_id bigint,p_reviewer text,p_note text default null)
returns text language plpgsql security invoker set search_path=public,pg_temp as $$
declare c public.model_activation_contracts_v1%rowtype; p public.model_promotion_candidate_packages_v1%rowtype;
begin
  if nullif(btrim(p_reviewer),'') is null then raise exception 'Reviewer is required'; end if;
  select * into c from public.model_activation_contracts_v1 where id=p_contract_id for update;
  if c.id is null then raise exception 'Activation contract % not found',p_contract_id; end if;
  if c.contract_status<>'draft' then raise exception 'Contract % must be draft, current=%',p_contract_id,c.contract_status; end if;
  select * into p from public.model_promotion_candidate_packages_v1 where id=c.promotion_package_id;
  if p.review_status<>'approved_for_promotion' then raise exception 'Promotion package % is not approved_for_promotion',p.id; end if;
  if c.max_abs_adjustment_pct>10 then raise exception 'v1 production guardrail may not exceed 10 percent'; end if;
  if not ('T-24h'=any(c.allowed_horizons)) or cardinality(c.allowed_horizons)<>1 then raise exception 'v1 contract allows T-24h only'; end if;
  if not c.fail_closed_to_champion or not c.kill_switch_enabled or not c.require_champion_parallel_forecast or not c.require_audit_payload then raise exception 'Required v1 safety controls are disabled'; end if;
  if c.execution_enabled then raise exception 'v1 contract execution must remain disabled'; end if;
  update public.model_activation_contracts_v1 set contract_status='ready_for_activation',reviewed_at=now(),reviewed_by=btrim(p_reviewer),review_note=p_note,updated_at=now() where id=p_contract_id;
  insert into public.model_activation_audit_log_v1(contract_id,action,actor,note,payload)
  values (p_contract_id,'contract_reviewed',btrim(p_reviewer),p_note,jsonb_build_object('status','ready_for_activation'));
  return 'ready_for_activation';
end;
$$;
revoke all on function public.review_model_activation_contract_v1(bigint,text,text) from public,anon,authenticated;
grant execute on function public.review_model_activation_contract_v1(bigint,text,text) to service_role;

create or replace function public.approve_model_activation_contract_v1(p_contract_id bigint,p_operator text,p_note text default null)
returns text language plpgsql security invoker set search_path=public,pg_temp as $$
declare c public.model_activation_contracts_v1%rowtype;
begin
  if nullif(btrim(p_operator),'') is null then raise exception 'Operator is required'; end if;
  select * into c from public.model_activation_contracts_v1 where id=p_contract_id for update;
  if c.id is null then raise exception 'Activation contract % not found',p_contract_id; end if;
  if c.contract_status<>'ready_for_activation' then raise exception 'Contract % must be ready_for_activation, current=%',p_contract_id,c.contract_status; end if;
  if c.writer_binding_status<>'not_bound' then raise exception 'Unexpected writer binding state for v1'; end if;
  if c.execution_enabled then raise exception 'v1 contract cannot enable execution'; end if;
  update public.model_activation_contracts_v1 set contract_status='activation_approved',activation_approved_at=now(),activation_approved_by=btrim(p_operator),activation_note=p_note,updated_at=now() where id=p_contract_id;
  insert into public.model_activation_audit_log_v1(contract_id,action,actor,note,payload)
  values (p_contract_id,'activation_approved',btrim(p_operator),p_note,jsonb_build_object('execution_enabled',false,'writer_binding_status','not_bound'));
  return 'activation_approved';
end;
$$;
revoke all on function public.approve_model_activation_contract_v1(bigint,text,text) from public,anon,authenticated;
grant execute on function public.approve_model_activation_contract_v1(bigint,text,text) to service_role;

create or replace function public.evaluate_model_activation_health_v1(p_contract_id bigint)
returns jsonb language plpgsql security invoker set search_path=public,pg_temp as $$
declare c public.model_activation_contracts_v1%rowtype; v_count integer; v_champion_mae numeric; v_challenger_mae numeric; v_ratio numeric; v_consecutive_worse integer:=0; r record; v_alert boolean:=false; v_reason text:=null;
begin
  select * into c from public.model_activation_contracts_v1 where id=p_contract_id;
  if c.id is null then raise exception 'Activation contract % not found',p_contract_id; end if;
  select count(*)::int,avg(champion_abs_error),avg(challenger_abs_error) into v_count,v_champion_mae,v_challenger_mae
  from (select * from public.model_activation_health_samples_v1 where contract_id=p_contract_id order by observed_at desc limit c.rolling_window_events) x;
  if v_count>0 and v_champion_mae>0 then v_ratio:=v_challenger_mae/v_champion_mae; end if;
  for r in select challenger_worse from public.model_activation_health_samples_v1 where contract_id=p_contract_id order by observed_at desc limit c.max_consecutive_worse_outcomes loop
    if r.challenger_worse then v_consecutive_worse:=v_consecutive_worse+1; else exit; end if;
  end loop;
  if v_count>=c.min_post_activation_outcomes and v_ratio is not null and v_ratio>c.max_rolling_mae_ratio_to_champion then
    v_alert:=true; v_reason:=format('rolling_mae_ratio %.3f exceeds %.3f',v_ratio,c.max_rolling_mae_ratio_to_champion);
  elsif v_consecutive_worse>=c.max_consecutive_worse_outcomes then
    v_alert:=true; v_reason:=format('%s consecutive worse outcomes',v_consecutive_worse);
  end if;
  if v_alert then
    insert into public.model_activation_audit_log_v1(contract_id,action,actor,note,payload)
    values (p_contract_id,'health_alert','system',v_reason,jsonb_build_object('sample_count',v_count,'champion_mae',v_champion_mae,'challenger_mae',v_challenger_mae,'mae_ratio',v_ratio,'consecutive_worse',v_consecutive_worse));
  end if;
  return jsonb_build_object('contract_id',p_contract_id,'sample_count',v_count,'champion_mae',v_champion_mae,'challenger_mae',v_challenger_mae,'mae_ratio',v_ratio,'consecutive_worse',v_consecutive_worse,'kill_switch_alert',v_alert,'reason',v_reason);
end;
$$;
revoke all on function public.evaluate_model_activation_health_v1(bigint) from public,anon,authenticated;
grant execute on function public.evaluate_model_activation_health_v1(bigint) to service_role;

