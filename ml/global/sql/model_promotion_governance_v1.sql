-- Beyond Ticketing — Model Promotion Governance v1
-- Gate crossing creates an immutable Ready for review evidence package.
-- This layer never activates a model and never changes production P50.

create table if not exists public.model_promotion_candidate_packages_v1 (
  id bigint generated by default as identity primary key,
  package_key text not null unique,
  category_key text not null,
  display_name text not null,
  candidate_key text not null,
  review_status text not null default 'ready_for_review'
    check (review_status in ('ready_for_review','approved_for_promotion','rejected','superseded')),
  primary_protocol text not null,
  research_prior_weight_pct numeric(5,2) not null,
  validation_event_count integer not null,
  validation_club_count integer,
  promotion_evidence_count integer not null,
  promotion_event_target integer not null,
  promotion_club_target integer,
  incumbent_mae numeric not null,
  bias_control_mae numeric,
  challenger_mae numeric not null,
  uplift_vs_incumbent numeric not null,
  incremental_uplift_vs_bias numeric,
  source_scorecard_refreshed_at timestamptz not null,
  source_evidence_refreshed_at timestamptz,
  frozen_at timestamptz not null default now(),
  decision_reason text not null,
  next_action text not null,
  evidence_frozen jsonb not null,
  supporting_evidence_frozen jsonb not null default '{}'::jsonb,
  auto_activation_allowed boolean not null default false check (auto_activation_allowed = false),
  reviewed_at timestamptz,
  reviewed_by text,
  review_note text,
  superseded_at timestamptz,
  superseded_by_package_id bigint references public.model_promotion_candidate_packages_v1(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_model_promotion_packages_status
  on public.model_promotion_candidate_packages_v1(review_status,frozen_at desc);
create index if not exists idx_model_promotion_packages_category
  on public.model_promotion_candidate_packages_v1(category_key,frozen_at desc);
create index if not exists idx_model_promotion_packages_superseded_by
  on public.model_promotion_candidate_packages_v1(superseded_by_package_id);

alter table public.model_promotion_candidate_packages_v1 enable row level security;
revoke all on public.model_promotion_candidate_packages_v1 from anon,authenticated;
grant select (
  id,package_key,category_key,display_name,candidate_key,review_status,primary_protocol,
  research_prior_weight_pct,validation_event_count,validation_club_count,promotion_evidence_count,
  promotion_event_target,promotion_club_target,incumbent_mae,bias_control_mae,challenger_mae,
  uplift_vs_incumbent,incremental_uplift_vs_bias,source_scorecard_refreshed_at,
  source_evidence_refreshed_at,frozen_at,decision_reason,next_action,auto_activation_allowed,
  reviewed_at,reviewed_by,review_note,superseded_at,superseded_by_package_id,created_at,updated_at
) on public.model_promotion_candidate_packages_v1 to anon,authenticated;
grant select,insert,update,delete on public.model_promotion_candidate_packages_v1 to service_role;
grant usage,select on sequence public.model_promotion_candidate_packages_v1_id_seq to service_role;

create policy dashboard_model_promotion_packages_read
on public.model_promotion_candidate_packages_v1
for select to anon,authenticated using (true);

create table if not exists public.model_promotion_review_log_v1 (
  id bigint generated by default as identity primary key,
  package_id bigint not null references public.model_promotion_candidate_packages_v1(id) on delete restrict,
  decision text not null check (decision in ('approved_for_promotion','rejected')),
  reviewer text not null,
  note text,
  decided_at timestamptz not null default now()
);
create index if not exists idx_model_promotion_review_log_package
  on public.model_promotion_review_log_v1(package_id,decided_at desc);
alter table public.model_promotion_review_log_v1 enable row level security;
revoke all on public.model_promotion_review_log_v1 from anon,authenticated;
grant select,insert on public.model_promotion_review_log_v1 to service_role;
grant usage,select on sequence public.model_promotion_review_log_v1_id_seq to service_role;

create or replace function public.guard_model_promotion_package_immutability_v1()
returns trigger
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
begin
  if new.package_key is distinct from old.package_key
     or new.category_key is distinct from old.category_key
     or new.display_name is distinct from old.display_name
     or new.candidate_key is distinct from old.candidate_key
     or new.primary_protocol is distinct from old.primary_protocol
     or new.research_prior_weight_pct is distinct from old.research_prior_weight_pct
     or new.validation_event_count is distinct from old.validation_event_count
     or new.validation_club_count is distinct from old.validation_club_count
     or new.promotion_evidence_count is distinct from old.promotion_evidence_count
     or new.promotion_event_target is distinct from old.promotion_event_target
     or new.promotion_club_target is distinct from old.promotion_club_target
     or new.incumbent_mae is distinct from old.incumbent_mae
     or new.bias_control_mae is distinct from old.bias_control_mae
     or new.challenger_mae is distinct from old.challenger_mae
     or new.uplift_vs_incumbent is distinct from old.uplift_vs_incumbent
     or new.incremental_uplift_vs_bias is distinct from old.incremental_uplift_vs_bias
     or new.source_scorecard_refreshed_at is distinct from old.source_scorecard_refreshed_at
     or new.source_evidence_refreshed_at is distinct from old.source_evidence_refreshed_at
     or new.frozen_at is distinct from old.frozen_at
     or new.decision_reason is distinct from old.decision_reason
     or new.next_action is distinct from old.next_action
     or new.evidence_frozen is distinct from old.evidence_frozen
     or new.supporting_evidence_frozen is distinct from old.supporting_evidence_frozen
     or new.auto_activation_allowed is distinct from old.auto_activation_allowed
     or new.created_at is distinct from old.created_at
  then
    raise exception 'Frozen promotion evidence cannot be modified';
  end if;
  new.updated_at:=now();
  return new;
end;
$$;
revoke all on function public.guard_model_promotion_package_immutability_v1() from public,anon,authenticated;
grant execute on function public.guard_model_promotion_package_immutability_v1() to service_role;

create trigger trg_guard_model_promotion_package_immutability_v1
before update on public.model_promotion_candidate_packages_v1
for each row execute function public.guard_model_promotion_package_immutability_v1();

create or replace function public.refresh_model_promotion_governance_v1()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  s public.model_evidence_scorecard_v1%rowtype;
  v_package_key text;
  v_new_id bigint;
  v_created integer:=0;
  v_support jsonb;
begin
  for s in
    select * from public.model_evidence_scorecard_v1
    where decision_status='promotable'
      and evidence_signal='positive'
      and promotion_progress_pct>=100
      and uplift_vs_incumbent>0
      and challenger_mae is not null
      and incumbent_mae is not null
      and challenger_mae<incumbent_mae
      and (bias_control_mae is null or challenger_mae<bias_control_mae)
    order by sort_order
  loop
    v_package_key:=concat_ws(':','promotion-v1',s.category_key,coalesce(s.candidate_key,'candidate'),
      coalesce(s.primary_protocol,'protocol'),s.promotion_evidence_count,
      coalesce(to_char(s.source_refreshed_at at time zone 'UTC','YYYYMMDDHH24MISS'),'nosource'));

    v_support:=case s.category_key
      when 'ticketing' then jsonb_build_object(
        'ticketing_protocols',coalesce((select jsonb_agg(to_jsonb(x) order by x.protocol) from public.ticketing_challenger_dashboard_summary_v1 x),'[]'::jsonb),
        'model',coalesce((select to_jsonb(m) from public.ticketing_challenger_models_v1 m order by trained_at desc limit 1),'{}'::jsonb))
      when 'sporting' then jsonb_build_object(
        'sporting_protocols',coalesce((select jsonb_agg(to_jsonb(x) order by x.protocol) from public.sporting_challenger_dashboard_summary_v1 x),'[]'::jsonb),
        'candidate',coalesce((select to_jsonb(c) from public.sporting_challenger_candidates_v1 c order by created_at desc limit 1),'{}'::jsonb))
      when 'match_context' then jsonb_build_object(
        'candidate_protocols',coalesce((select jsonb_agg(to_jsonb(x) order by x.protocol) from public.match_context_challenger_dashboard_v1 x where x.feature_key=s.candidate_key),'[]'::jsonb),
        'feature_readiness',coalesce((select jsonb_agg(to_jsonb(r) order by r.feature_key) from public.match_context_feature_readiness_v1 r),'[]'::jsonb))
      when 'hype' then jsonb_build_object(
        'hype_summary',coalesce((select to_jsonb(h) from public.hype_challenger_summary_v1 h order by refreshed_at desc limit 1),'{}'::jsonb),
        'candidate_protocols',coalesce((select jsonb_agg(to_jsonb(x) order by x.protocol) from public.hype_challenger_cv_summary_v1 x where x.feature_key=s.candidate_key),'[]'::jsonb))
      when 'weather' then jsonb_build_object(
        'weather_study',coalesce((select to_jsonb(w) from public.weather_signal_study_reports w order by generated_at desc limit 1),'{}'::jsonb))
      else '{}'::jsonb end;

    insert into public.model_promotion_candidate_packages_v1(
      package_key,category_key,display_name,candidate_key,review_status,primary_protocol,
      research_prior_weight_pct,validation_event_count,validation_club_count,promotion_evidence_count,
      promotion_event_target,promotion_club_target,incumbent_mae,bias_control_mae,challenger_mae,
      uplift_vs_incumbent,incremental_uplift_vs_bias,source_scorecard_refreshed_at,
      source_evidence_refreshed_at,decision_reason,next_action,evidence_frozen,
      supporting_evidence_frozen,auto_activation_allowed
    ) values (
      v_package_key,s.category_key,s.display_name,coalesce(s.candidate_key,'candidate'),'ready_for_review',
      coalesce(s.primary_protocol,'unknown'),s.research_prior_weight_pct,coalesce(s.validation_event_count,0),
      s.validation_club_count,s.promotion_evidence_count,s.promotion_event_target,s.promotion_club_target,
      s.incumbent_mae,s.bias_control_mae,s.challenger_mae,s.uplift_vs_incumbent,
      s.incremental_uplift_vs_bias,s.refreshed_at,s.source_refreshed_at,s.decision_reason,s.next_action,
      to_jsonb(s),v_support,false
    ) on conflict (package_key) do nothing returning id into v_new_id;

    if v_new_id is not null then
      update public.model_promotion_candidate_packages_v1
      set review_status='superseded',superseded_at=now(),superseded_by_package_id=v_new_id
      where category_key=s.category_key and id<>v_new_id and review_status='ready_for_review';
      v_created:=v_created+1;
    end if;
    v_new_id:=null;
  end loop;
  return v_created;
end;
$$;
revoke all on function public.refresh_model_promotion_governance_v1() from public,anon,authenticated;
grant execute on function public.refresh_model_promotion_governance_v1() to service_role;

create or replace function public.review_model_promotion_candidate_v1(
  p_package_id bigint,p_decision text,p_reviewer text,p_note text default null
)
returns text
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare v_status text;
begin
  if p_decision not in ('approved_for_promotion','rejected') then
    raise exception 'Decision must be approved_for_promotion or rejected';
  end if;
  if nullif(btrim(p_reviewer),'') is null then raise exception 'Reviewer is required'; end if;

  select review_status into v_status
  from public.model_promotion_candidate_packages_v1
  where id=p_package_id for update;

  if v_status is null then raise exception 'Promotion package % not found',p_package_id; end if;
  if v_status<>'ready_for_review' then
    raise exception 'Promotion package % is not ready for review (status=%)',p_package_id,v_status;
  end if;

  update public.model_promotion_candidate_packages_v1
  set review_status=p_decision,reviewed_at=now(),reviewed_by=btrim(p_reviewer),review_note=p_note
  where id=p_package_id;

  insert into public.model_promotion_review_log_v1(package_id,decision,reviewer,note)
  values (p_package_id,p_decision,btrim(p_reviewer),p_note);
  return p_decision;
end;
$$;
revoke all on function public.review_model_promotion_candidate_v1(bigint,text,text,text) from public,anon,authenticated;
grant execute on function public.review_model_promotion_candidate_v1(bigint,text,text,text) to service_role;

create or replace view public.dashboard_model_promotion_queue_v1
with (security_invoker=true)
as
select id,package_key,category_key,display_name,candidate_key,review_status,primary_protocol,
  research_prior_weight_pct,validation_event_count,validation_club_count,promotion_evidence_count,
  promotion_event_target,promotion_club_target,incumbent_mae,bias_control_mae,challenger_mae,
  uplift_vs_incumbent,incremental_uplift_vs_bias,source_scorecard_refreshed_at,
  source_evidence_refreshed_at,frozen_at,decision_reason,next_action,auto_activation_allowed,
  reviewed_at,reviewed_by,review_note,superseded_at,superseded_by_package_id,created_at,updated_at
from public.model_promotion_candidate_packages_v1
order by case review_status when 'ready_for_review' then 0 when 'approved_for_promotion' then 1 when 'rejected' then 2 else 3 end,
  frozen_at desc;
revoke all on public.dashboard_model_promotion_queue_v1 from public;
grant select on public.dashboard_model_promotion_queue_v1 to anon,authenticated,service_role;

create or replace view public.dashboard_model_promotion_governance_summary_v1
with (security_invoker=true)
as
with q as (
  select count(*)::int total_packages,
    count(*) filter (where review_status='ready_for_review')::int ready_for_review_count,
    count(*) filter (where review_status='approved_for_promotion')::int approved_count,
    count(*) filter (where review_status='rejected')::int rejected_count,
    count(*) filter (where review_status='superseded')::int superseded_count,
    max(frozen_at) latest_frozen_at
  from public.model_promotion_candidate_packages_v1
), nearest as (
  select category_key,display_name,promotion_progress_pct,promotion_evidence_count,promotion_event_target,evidence_signal
  from public.model_evidence_scorecard_v1
  where decision_status='collecting'
  order by promotion_progress_pct desc,sort_order
  limit 1
)
select q.total_packages,q.ready_for_review_count,q.approved_count,q.rejected_count,q.superseded_count,
  q.latest_frozen_at,n.category_key nearest_category_key,n.display_name nearest_display_name,
  n.promotion_progress_pct nearest_progress_pct,n.promotion_evidence_count nearest_evidence_count,
  n.promotion_event_target nearest_event_target,n.evidence_signal nearest_evidence_signal,
  'Gate crossing creates a frozen Ready for review package. Approval never changes P50 automatically.'::text governance_note
from q left join nearest n on true;
revoke all on public.dashboard_model_promotion_governance_summary_v1 from public;
grant select on public.dashboard_model_promotion_governance_summary_v1 to anon,authenticated,service_role;

