create or replace function public.refresh_media_attention_context_v02()
returns integer
language plpgsql
security invoker
set search_path=public,pg_temp
as $$
declare
  r record;
  v_rows integer := 0;
  v_accel numeric;
  v_status text;
begin
  for r in
    with stats as (
      select
        ticket_event_id,
        sum(union_mentions_pl) filter (where sample_at>=now()-interval '24 hours')::numeric as union_24h,
        sum(pair_mentions_pl) filter (where sample_at>=now()-interval '24 hours')::numeric as pair_24h,
        count(*) filter (where sample_at>=now()-interval '24 hours')::int as samples_24h,
        sum(union_mentions_pl) filter (where sample_at>=now()-interval '48 hours' and sample_at<now()-interval '24 hours')::numeric as union_prev24h,
        count(*) filter (where sample_at>=now()-interval '48 hours' and sample_at<now()-interval '24 hours')::int as samples_prev24h,
        max(sample_at) as latest_sample_at,
        max(source_file_timestamp) as latest_source_file_timestamp
      from public.media_attention_samples_v2
      where sample_at>=now()-interval '48 hours'
      group by ticket_event_id
    )
    select * from stats
  loop
    if coalesce(r.samples_24h,0)>=4 and coalesce(r.samples_prev24h,0)>=4
       and (coalesce(r.union_24h,0)+coalesce(r.union_prev24h,0))>0 then
      v_accel := round(((coalesce(r.union_24h,0)/r.samples_24h)+0.25)
        /((coalesce(r.union_prev24h,0)/r.samples_prev24h)+0.25),4);
    else
      v_accel := null;
    end if;

    v_status := case
      when coalesce(r.samples_24h,0)<4 then 'warmup_current_window'
      when coalesce(r.samples_prev24h,0)<4 then 'warmup_comparison_window'
      when coalesce(r.union_24h,0)=0 and coalesce(r.union_prev24h,0)=0 then 'no_detected_attention_in_sampled_windows'
      when v_accel is null then 'collecting_comparison_baseline'
      else 'comparison_ready'
    end;

    insert into public.event_context_observations(
      ticket_event_id,feature_key,observed_at,numeric_value,text_value,
      source_name,source_url,source_observed_at,source_record_key,confidence,metadata
    ) values (
      r.ticket_event_id,'hype.media_attention',r.latest_sample_at,coalesce(r.union_24h,0),
      format('Broad event-team media attention v2: %s polskich publikacji w próbkach 24h; %s publikacji wymienia oba kluby.',coalesce(r.union_24h,0)::int,coalesce(r.pair_24h,0)::int),
      'GDELT Web News NGrams v2 broad event-team attention',
      'https://data.gdeltproject.org/gdeltv5/weblegacy/ngrams/',r.latest_source_file_timestamp,
      format('gdelt-ngram:v02:media:%s:%s',r.ticket_event_id,to_char(r.latest_sample_at at time zone 'UTC','YYYYMMDD"T"HH24MI')),
      case when coalesce(r.samples_24h,0)>=12 then 0.70 when coalesce(r.samples_24h,0)>=4 then 0.60 else 0.45 end,
      jsonb_build_object('signal_version','v2','signal_type','broad_event_team_attention',
        'union_mentions_24h',coalesce(r.union_24h,0),'pair_mentions_24h',coalesce(r.pair_24h,0),
        'samples_24h',coalesce(r.samples_24h,0),'union_mentions_previous_24h',coalesce(r.union_prev24h,0),
        'samples_previous_24h',coalesce(r.samples_prev24h,0),'acceleration_ratio',v_accel,
        'readiness_status',v_status,'scoring_status','prospective_raw_attention_not_model_scored',
        'production_impact','none_shadow_only')
    ) on conflict (ticket_event_id,feature_key,source_name,source_record_key)
    do update set observed_at=excluded.observed_at,numeric_value=excluded.numeric_value,text_value=excluded.text_value,
      source_observed_at=excluded.source_observed_at,confidence=excluded.confidence,metadata=excluded.metadata;

    if v_accel is not null then
      insert into public.event_context_observations(
        ticket_event_id,feature_key,observed_at,numeric_value,text_value,
        source_name,source_url,source_observed_at,source_record_key,confidence,metadata
      ) values (
        r.ticket_event_id,'hype.mention_acceleration',r.latest_sample_at,v_accel,
        format('Broad event-team attention tempo v2: %s× vs previous sampled 24h window.',to_char(v_accel,'FM999990.00')),
        'GDELT Web News NGrams v2 broad event-team attention',
        'https://data.gdeltproject.org/gdeltv5/weblegacy/ngrams/',r.latest_source_file_timestamp,
        format('gdelt-ngram:v02:accel:%s:%s',r.ticket_event_id,to_char(r.latest_sample_at at time zone 'UTC','YYYYMMDD"T"HH24MI')),
        case when coalesce(r.samples_24h,0)>=12 and coalesce(r.samples_prev24h,0)>=12 then 0.70 else 0.60 end,
        jsonb_build_object('signal_version','v2','signal_type','broad_event_team_attention_acceleration',
          'acceleration_ratio',v_accel,'samples_24h',coalesce(r.samples_24h,0),
          'samples_previous_24h',coalesce(r.samples_prev24h,0),'scoring_status','prospective_raw_attention_not_model_scored',
          'production_impact','none_shadow_only')
      ) on conflict (ticket_event_id,feature_key,source_name,source_record_key)
      do update set observed_at=excluded.observed_at,numeric_value=excluded.numeric_value,text_value=excluded.text_value,
        source_observed_at=excluded.source_observed_at,confidence=excluded.confidence,metadata=excluded.metadata;
    end if;
    v_rows := v_rows+1;
  end loop;
  return v_rows;
end;
$$;

