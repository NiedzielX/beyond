create table if not exists public.media_attention_samples_v2 (
  id bigint generated by default as identity primary key,
  ticket_event_id bigint not null references public.ticket_events(id) on delete cascade,
  sample_at timestamptz not null,
  source_file_timestamp timestamptz not null,
  source_file_url text not null,
  union_mentions_pl integer not null check (union_mentions_pl>=0),
  pair_mentions_pl integer not null check (pair_mentions_pl>=0),
  home_mentions_pl integer not null check (home_mentions_pl>=0),
  away_mentions_pl integer not null check (away_mentions_pl>=0),
  pair_docs_global integer not null check (pair_docs_global>=0),
  union_docs_global integer not null check (union_docs_global>=0),
  source_name text not null default 'GDELT Web News NGrams v2',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(ticket_event_id,source_file_timestamp)
);

create index if not exists idx_media_attention_samples_v2_event_time
  on public.media_attention_samples_v2(ticket_event_id,sample_at desc);

