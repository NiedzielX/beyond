-- Beyond Ticketing Event Context Layer v0.1
-- Target: final attendance / demand pressure research layer.
-- Important: weights below are heuristic research priors, NOT trained model coefficients.
-- Weather remains shadow-only until it demonstrates positive out-of-sample uplift.

create table if not exists public.context_matrix_versions (
    version text primary key,
    target_metric text not null,
    status text not null check (status in ('draft','frozen','retired')),
    description text,
    created_at timestamptz not null default now()
);

create table if not exists public.context_feature_definitions (
    feature_key text primary key,
    group_key text not null,
    display_name text not null,
    description text,
    value_type text not null check (value_type in ('numeric','boolean','categorical','text')),
    production_role text not null check (production_role in ('active_prior','shadow','data_quality_modifier','reference_only')),
    refresh_cadence text,
    primary_source text,
    fallback_source text,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.context_feature_weights (
    matrix_version text not null references public.context_matrix_versions(version) on delete cascade,
    feature_key text not null references public.context_feature_definitions(feature_key) on delete cascade,
    weight_pct numeric(6,3) not null default 0,
    rationale text,
    primary key (matrix_version, feature_key),
    check (weight_pct >= 0 and weight_pct <= 100)
);

create index if not exists idx_context_feature_weights_feature_key
    on public.context_feature_weights(feature_key);

create table if not exists public.event_context_observations (
    id bigint generated by default as identity primary key,
    ticket_event_id bigint not null references public.ticket_events(id) on delete cascade,
    feature_key text not null references public.context_feature_definitions(feature_key),
    observed_at timestamptz not null,
    numeric_value numeric,
    boolean_value boolean,
    text_value text,
    normalized_score numeric(7,4),
    source_name text not null,
    source_url text,
    source_observed_at timestamptz,
    confidence numeric(5,4),
    source_record_key text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    check (normalized_score is null or (normalized_score >= -1 and normalized_score <= 1)),
    check (confidence is null or (confidence >= 0 and confidence <= 1)),
    check (
        (numeric_value is not null)::int +
        (boolean_value is not null)::int +
        (text_value is not null)::int >= 1
    )
);

create index if not exists idx_event_context_event_feature_time
    on public.event_context_observations(ticket_event_id, feature_key, observed_at desc);

create index if not exists idx_event_context_feature_time
    on public.event_context_observations(feature_key, observed_at desc);

create unique index if not exists uq_event_context_source_record
    on public.event_context_observations(ticket_event_id, feature_key, source_name, source_record_key)
    where source_record_key is not null;

alter table public.context_matrix_versions enable row level security;
alter table public.context_feature_definitions enable row level security;
alter table public.context_feature_weights enable row level security;
alter table public.event_context_observations enable row level security;

revoke all on table public.context_matrix_versions from anon, authenticated;
revoke all on table public.context_feature_definitions from anon, authenticated;
revoke all on table public.context_feature_weights from anon, authenticated;
revoke all on table public.event_context_observations from anon, authenticated;

grant select, insert, update, delete on table public.context_matrix_versions to service_role;
grant select, insert, update, delete on table public.context_feature_definitions to service_role;
grant select, insert, update, delete on table public.context_feature_weights to service_role;
grant select, insert, update, delete on table public.event_context_observations to service_role;
grant usage, select on all sequences in schema public to service_role;

