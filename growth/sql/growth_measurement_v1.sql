create or replace function public.create_growth_experiment_draft_v1(
  p_experiment_key text,p_ticket_event_id bigint,p_play text,p_hypothesis text,p_action_description text,p_actor text,
  p_primary_metric text default 'incremental_gross_revenue',p_assignment_method text default 'randomized_holdout',
  p_currency text default 'PLN',p_min_exposed_per_arm integer default 100,p_treatment_share_pct numeric default 90,
  p_holdout_share_pct numeric default 10,p_recommendation_snapshot jsonb default '{}'::jsonb
)
returns bigint language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_id bigint;
begin
  if nullif(btrim(p_experiment_key),'') is null then raise exception 'experiment_key required'; end if;
  if nullif(btrim(p_actor),'') is null then raise exception 'actor required'; end if;
  if abs((p_treatment_share_pct+p_holdout_share_pct)-100) > 0.001 then raise exception 'Treatment + holdout shares must equal 100'; end if;
  if p_treatment_share_pct<=0 or p_holdout_share_pct<=0 then raise exception 'Both arms must be positive'; end if;
  perform 1 from public.ticket_events where id=p_ticket_event_id;
  if not found then raise exception 'ticket_event_id % not found',p_ticket_event_id; end if;
  insert into public.growth_experiments_v1(experiment_key,ticket_event_id,play,hypothesis,action_description,primary_metric,assignment_method,currency,min_exposed_per_arm,recommendation_snapshot,created_by)
  values(btrim(p_experiment_key),p_ticket_event_id,p_play,p_hypothesis,p_action_description,p_primary_metric,p_assignment_method,upper(p_currency),p_min_exposed_per_arm,coalesce(p_recommendation_snapshot,'{}'::jsonb),btrim(p_actor))
  returning id into v_id;
  insert into public.growth_experiment_arms_v1(experiment_id,arm_key,arm_label,planned_share_pct,treatment_description)
  values (v_id,'treatment','Treatment',p_treatment_share_pct,p_action_description),(v_id,'holdout','Holdout',p_holdout_share_pct,'No Growth intervention; business-as-usual control.');
  insert into public.growth_experiment_audit_log_v1(experiment_id,action,actor,note,payload)
  values(v_id,'created',btrim(p_actor),'Draft created; no external action executed.',jsonb_build_object('auto_execution_allowed',false));
  return v_id;
end;
$$;

create or replace function public.plan_growth_experiment_v1(p_experiment_id bigint,p_actor text,p_start_at timestamptz,p_end_at timestamptz,p_note text default null)
returns text language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_share numeric; v_arms integer; v_status text;
begin
  if nullif(btrim(p_actor),'') is null then raise exception 'actor required'; end if;
  if p_end_at is not null and p_start_at is not null and p_end_at<=p_start_at then raise exception 'end must be after start'; end if;
  select status into v_status from public.growth_experiments_v1 where id=p_experiment_id for update;
  if v_status is null then raise exception 'experiment % not found',p_experiment_id; end if;
  if v_status<>'draft' then raise exception 'experiment must be draft, current=%',v_status; end if;
  select count(*)::int,sum(planned_share_pct) into v_arms,v_share from public.growth_experiment_arms_v1 where experiment_id=p_experiment_id;
  if v_arms<>2 or abs(v_share-100)>0.001 then raise exception 'experiment requires treatment + holdout totaling 100 percent'; end if;
  update public.growth_experiments_v1 set status='planned',planned_start_at=p_start_at,planned_end_at=p_end_at,approved_by=btrim(p_actor),approved_at=now(),updated_at=now(),notes=coalesce(p_note,notes) where id=p_experiment_id;
  insert into public.growth_experiment_audit_log_v1(experiment_id,action,actor,note) values(p_experiment_id,'planned',btrim(p_actor),p_note);
  return 'planned';
end;
$$;

create or replace function public.start_growth_experiment_v1(p_experiment_id bigint,p_actor text,p_note text default null)
returns text language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_status text;
begin
  if nullif(btrim(p_actor),'') is null then raise exception 'actor required'; end if;
  select status into v_status from public.growth_experiments_v1 where id=p_experiment_id for update;
  if v_status is null then raise exception 'experiment % not found',p_experiment_id; end if;
  if v_status<>'planned' then raise exception 'experiment must be planned, current=%',v_status; end if;
  update public.growth_experiments_v1 set status='running',actual_start_at=now(),started_by=btrim(p_actor),updated_at=now(),notes=coalesce(p_note,notes) where id=p_experiment_id;
  insert into public.growth_experiment_audit_log_v1(experiment_id,action,actor,note,payload) values(p_experiment_id,'started',btrim(p_actor),p_note,jsonb_build_object('external_execution','tracked_only_not_performed_by_beyond'));
  return 'running';
end;
$$;

create or replace function public.complete_growth_experiment_v1(p_experiment_id bigint,p_actor text,p_note text default null)
returns text language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_status text;
begin
  if nullif(btrim(p_actor),'') is null then raise exception 'actor required'; end if;
  select status into v_status from public.growth_experiments_v1 where id=p_experiment_id for update;
  if v_status is null then raise exception 'experiment % not found',p_experiment_id; end if;
  if v_status not in ('planned','running') then raise exception 'experiment must be planned or running, current=%',v_status; end if;
  update public.growth_experiments_v1 set status='completed',actual_end_at=now(),completed_by=btrim(p_actor),updated_at=now(),notes=coalesce(p_note,notes) where id=p_experiment_id;
  insert into public.growth_experiment_audit_log_v1(experiment_id,action,actor,note) values(p_experiment_id,'completed',btrim(p_actor),p_note);
  return 'completed';
end;
$$;

create or replace function public.record_growth_arm_observation_v1(
  p_experiment_id bigint,p_arm_key text,p_exposed_count integer,p_purchasers_count integer,p_tickets_count integer,
  p_gross_ticket_revenue numeric,p_refunds_amount numeric,p_campaign_cost numeric,p_data_source text,p_source_record_key text,
  p_actor text,p_observed_at timestamptz default now(),p_metadata jsonb default '{}'::jsonb
)
returns bigint language plpgsql security invoker set search_path=public,pg_temp as $$
declare v_arm_id bigint; v_status text; v_prev public.growth_experiment_arm_observations_v1%rowtype; v_id bigint;
begin
  if p_arm_key not in ('treatment','holdout') then raise exception 'arm_key must be treatment or holdout'; end if;
  if nullif(btrim(p_data_source),'') is null then raise exception 'data_source required'; end if;
  if nullif(btrim(p_source_record_key),'') is null then raise exception 'source_record_key required'; end if;
  if nullif(btrim(p_actor),'') is null then raise exception 'actor required'; end if;
  if p_exposed_count<0 or p_purchasers_count<0 or p_tickets_count<0 then raise exception 'counts must be non-negative'; end if;
  if p_purchasers_count>p_exposed_count then raise exception 'purchasers may not exceed exposed'; end if;
  if p_tickets_count<p_purchasers_count then raise exception 'tickets may not be lower than purchasers'; end if;
  if p_gross_ticket_revenue<0 or p_refunds_amount<0 or p_campaign_cost<0 then raise exception 'financial values must be non-negative'; end if;
  select e.status,a.id into v_status,v_arm_id from public.growth_experiments_v1 e join public.growth_experiment_arms_v1 a on a.experiment_id=e.id where e.id=p_experiment_id and a.arm_key=p_arm_key;
  if v_arm_id is null then raise exception 'experiment % arm % not found',p_experiment_id,p_arm_key; end if;
  if v_status not in ('running','completed') then raise exception 'observations allowed only for running/completed experiment, current=%',v_status; end if;
  select * into v_prev from public.growth_experiment_arm_observations_v1 where arm_id=v_arm_id order by observed_at desc,id desc limit 1;
  if v_prev.id is not null then
    if p_exposed_count<v_prev.exposed_count then raise exception 'cumulative exposed_count may not decrease'; end if;
    if p_purchasers_count<v_prev.purchasers_count then raise exception 'cumulative purchasers_count may not decrease'; end if;
    if p_tickets_count<v_prev.tickets_count then raise exception 'cumulative tickets_count may not decrease'; end if;
    if p_gross_ticket_revenue<v_prev.gross_ticket_revenue then raise exception 'cumulative gross_ticket_revenue may not decrease'; end if;
    if p_refunds_amount<v_prev.refunds_amount then raise exception 'cumulative refunds_amount may not decrease'; end if;
    if p_campaign_cost<v_prev.campaign_cost then raise exception 'cumulative campaign_cost may not decrease'; end if;
    if p_observed_at<v_prev.observed_at then raise exception 'observed_at may not move backwards'; end if;
  end if;
  insert into public.growth_experiment_arm_observations_v1(arm_id,observed_at,exposed_count,purchasers_count,tickets_count,gross_ticket_revenue,refunds_amount,campaign_cost,data_source,source_record_key,metadata)
  values(v_arm_id,p_observed_at,p_exposed_count,p_purchasers_count,p_tickets_count,p_gross_ticket_revenue,p_refunds_amount,p_campaign_cost,btrim(p_data_source),btrim(p_source_record_key),coalesce(p_metadata,'{}'::jsonb))
  on conflict (arm_id,source_record_key) do update set observed_at=excluded.observed_at,exposed_count=excluded.exposed_count,purchasers_count=excluded.purchasers_count,tickets_count=excluded.tickets_count,gross_ticket_revenue=excluded.gross_ticket_revenue,refunds_amount=excluded.refunds_amount,campaign_cost=excluded.campaign_cost,data_source=excluded.data_source,metadata=excluded.metadata
  returning id into v_id;
  insert into public.growth_experiment_audit_log_v1(experiment_id,action,actor,note,payload)
  values(p_experiment_id,'observation_recorded',btrim(p_actor),format('%s observation recorded from %s',p_arm_key,btrim(p_data_source)),jsonb_build_object('arm_key',p_arm_key,'observation_id',v_id,'source_record_key',p_source_record_key,'observed_at',p_observed_at));
  return v_id;
end;
$$;

