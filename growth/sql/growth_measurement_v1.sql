create or replace view public.dashboard_growth_experiment_measurement_v1 with (security_invoker=true) as
with latest as (
  select distinct on (o.arm_id) o.arm_id,o.observed_at,o.exposed_count,o.purchasers_count,o.tickets_count,o.gross_ticket_revenue,o.refunds_amount,o.campaign_cost,o.data_source
  from public.growth_experiment_arm_observations_v1 o order by o.arm_id,o.observed_at desc,o.id desc
), pivot as (
  select e.id experiment_id,e.experiment_key,e.ticket_event_id,e.play,e.status,e.hypothesis,e.action_description,e.primary_metric,e.assignment_method,e.currency,e.min_exposed_per_arm,
    te.home_team,te.away_team,te.kickoff_at,
    max(case when a.arm_key='treatment' then a.planned_share_pct end) treatment_share_pct,
    max(case when a.arm_key='holdout' then a.planned_share_pct end) holdout_share_pct,
    max(case when a.arm_key='treatment' then l.observed_at end) treatment_observed_at,
    max(case when a.arm_key='holdout' then l.observed_at end) holdout_observed_at,
    max(case when a.arm_key='treatment' then l.exposed_count end) treatment_exposed,
    max(case when a.arm_key='holdout' then l.exposed_count end) holdout_exposed,
    max(case when a.arm_key='treatment' then l.purchasers_count end) treatment_purchasers,
    max(case when a.arm_key='holdout' then l.purchasers_count end) holdout_purchasers,
    max(case when a.arm_key='treatment' then l.tickets_count end) treatment_tickets,
    max(case when a.arm_key='holdout' then l.tickets_count end) holdout_tickets,
    max(case when a.arm_key='treatment' then l.gross_ticket_revenue end) treatment_gross_revenue,
    max(case when a.arm_key='holdout' then l.gross_ticket_revenue end) holdout_gross_revenue,
    max(case when a.arm_key='treatment' then l.refunds_amount end) treatment_refunds,
    max(case when a.arm_key='holdout' then l.refunds_amount end) holdout_refunds,
    max(case when a.arm_key='treatment' then l.campaign_cost end) treatment_campaign_cost,
    max(case when a.arm_key='holdout' then l.campaign_cost end) holdout_campaign_cost,
    max(case when a.arm_key='treatment' then l.data_source end) treatment_data_source,
    max(case when a.arm_key='holdout' then l.data_source end) holdout_data_source
  from public.growth_experiments_v1 e join public.ticket_events te on te.id=e.ticket_event_id join public.growth_experiment_arms_v1 a on a.experiment_id=e.id left join latest l on l.arm_id=a.id
  group by e.id,e.experiment_key,e.ticket_event_id,e.play,e.status,e.hypothesis,e.action_description,e.primary_metric,e.assignment_method,e.currency,e.min_exposed_per_arm,te.home_team,te.away_team,te.kickoff_at
), calc as (
  select p.*,
    case when treatment_exposed>0 then treatment_purchasers::numeric/treatment_exposed end treatment_conversion_rate,
    case when holdout_exposed>0 then holdout_purchasers::numeric/holdout_exposed end holdout_conversion_rate,
    case when treatment_exposed>0 then treatment_tickets::numeric/treatment_exposed end treatment_ticket_rate,
    case when holdout_exposed>0 then holdout_tickets::numeric/holdout_exposed end holdout_ticket_rate,
    case when treatment_exposed>0 then treatment_gross_revenue/treatment_exposed end treatment_gross_revenue_per_exposed,
    case when holdout_exposed>0 then holdout_gross_revenue/holdout_exposed end holdout_gross_revenue_per_exposed,
    case when treatment_exposed>0 then (treatment_gross_revenue-coalesce(treatment_refunds,0))/treatment_exposed end treatment_net_revenue_per_exposed,
    case when holdout_exposed>0 then (holdout_gross_revenue-coalesce(holdout_refunds,0))/holdout_exposed end holdout_net_revenue_per_exposed
  from pivot p
)
select c.*,
  case when treatment_exposed is null or holdout_exposed is null then 'awaiting_data'
       when treatment_exposed<min_exposed_per_arm or holdout_exposed<min_exposed_per_arm then 'collecting_sample'
       when assignment_method='manual_noncausal' then 'descriptive_only' else 'experiment_observed' end measurement_status,
  case when assignment_method='randomized_holdout' then 'randomized' when assignment_method='geo_holdout' then 'holdout_design' when assignment_method='quasi_experimental' then 'quasi_experimental' else 'noncausal' end evidence_design,
  case when treatment_exposed>0 and holdout_exposed>0 then (treatment_ticket_rate-holdout_ticket_rate)*treatment_exposed end incremental_tickets_treatment_population,
  case when treatment_exposed>0 and holdout_exposed>0 then (treatment_gross_revenue_per_exposed-holdout_gross_revenue_per_exposed)*treatment_exposed end incremental_gross_revenue,
  case when treatment_exposed>0 and holdout_exposed>0 then (treatment_net_revenue_per_exposed-holdout_net_revenue_per_exposed)*treatment_exposed end incremental_net_revenue,
  case when treatment_exposed>0 and holdout_exposed>0 then coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_exposed,0))*treatment_exposed end incremental_campaign_cost,
  case when treatment_exposed>0 and holdout_exposed>0 then ((treatment_net_revenue_per_exposed-holdout_net_revenue_per_exposed)*treatment_exposed)-(coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_exposed,0))*treatment_exposed) end incremental_contribution,
  case when treatment_exposed>0 and holdout_exposed>0 and (coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_exposed,0))*treatment_exposed)>0 then
    (((treatment_net_revenue_per_exposed-holdout_net_revenue_per_exposed)*treatment_exposed)-(coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_exposed,0))*treatment_exposed)) /
    (coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_exposed,0))*treatment_exposed) end roi_on_incremental_campaign_cost,
  case when treatment_exposed is null or holdout_exposed is null then 'No treatment/holdout outcome data yet.'
       when treatment_exposed<min_exposed_per_arm or holdout_exposed<min_exposed_per_arm then 'Below operational exposure gate; uplift is directional only.'
       when assignment_method='manual_noncausal' then 'Descriptive comparison only; no causal claim allowed.'
       else 'Raw experiment uplift available; statistical significance is not assessed in v1.' end interpretation_note
from calc c;
revoke all on public.dashboard_growth_experiment_measurement_v1 from public;
grant select on public.dashboard_growth_experiment_measurement_v1 to anon,authenticated,service_role;

create or replace view public.dashboard_growth_experiment_summary_v1 with (security_invoker=true) as
select count(*)::int experiment_count,
  count(*) filter (where status='draft')::int draft_count,
  count(*) filter (where status='planned')::int planned_count,
  count(*) filter (where status='running')::int running_count,
  count(*) filter (where status='completed')::int completed_count,
  count(*) filter (where measurement_status='experiment_observed')::int measured_experiment_count,
  count(*) filter (where measurement_status='collecting_sample')::int collecting_sample_count,
  count(*) filter (where measurement_status='awaiting_data')::int awaiting_data_count,
  sum(incremental_tickets_treatment_population) filter (where measurement_status in ('experiment_observed','descriptive_only')) total_incremental_tickets_directional,
