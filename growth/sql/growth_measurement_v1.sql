-- Beyond Growth — Measurement v1
-- Aggregate-only treatment/holdout experiment tracking. No PII. No campaign execution.

create table if not exists public.growth_experiments_v1 (
  id bigint generated by default as identity primary key,
  experiment_key text not null unique,
  ticket_event_id bigint not null references public.ticket_events(id) on delete restrict,
  play text not null check (play in ('protect_yield','demand_activation','last_mile_conversion','monitor','hold_data_quality')),
  status text not null default 'draft' check (status in ('draft','planned','running','completed','cancelled')),
  hypothesis text not null,
  action_description text not null,
  primary_metric text not null default 'incremental_gross_revenue' check (primary_metric in ('incremental_tickets','incremental_gross_revenue','incremental_net_revenue','incremental_contribution')),
  assignment_method text not null default 'randomized_holdout' check (assignment_method in ('randomized_holdout','geo_holdout','quasi_experimental','manual_noncausal')),
  currency text not null default 'PLN' check (currency ~ '^[A-Z]{3}$'),
  min_exposed_per_arm integer not null default 100 check (min_exposed_per_arm >= 1),
  planned_start_at timestamptz,
  planned_end_at timestamptz,
  actual_start_at timestamptz,
  actual_end_at timestamptz,
  recommendation_snapshot jsonb not null default '{}'::jsonb,
  auto_execution_allowed boolean not null default false check (auto_execution_allowed = false),
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  approved_by text,
  approved_at timestamptz,
  started_by text,
  completed_by text,
  notes text
);
create index if not exists idx_growth_experiments_event_status on public.growth_experiments_v1(ticket_event_id,status,created_at desc);
