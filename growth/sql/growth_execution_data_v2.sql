-- Beyond Growth — Execution Data v2
-- Adds assignment-aware, intent-to-treat measurement and a protected batch ingest contract.
-- Raw customer PII is intentionally not stored. Exact manifests use upstream-generated pseudonymous hashes.

alter table public.growth_experiments_v1
  add column if not exists min_assigned_per_arm integer not null default 100 check (min_assigned_per_arm >= 1);

alter table public.growth_experiment_arm_observations_v1
  add column if not exists assigned_count integer,
  add column if not exists assignment_manifest_count integer;

alter table public.growth_experiment_arm_observations_v1
  drop constraint if exists growth_experiment_arm_observations_v1_check;

alter table public.growth_experiment_arm_observations_v1
  add constraint growth_arm_observation_assigned_nonnegative_v2 check (assigned_count is null or assigned_count >= 0),
  add constraint growth_arm_observation_manifest_nonnegative_v2 check (assignment_manifest_count is null or assignment_manifest_count >= 0),
  add constraint growth_arm_observation_exposed_within_assigned_v2 check (assigned_count is null or exposed_count <= assigned_count),
  add constraint growth_arm_observation_purchasers_within_assigned_v2 check (assigned_count is null or purchasers_count <= assigned_count),
  add constraint growth_arm_observation_refunds_within_gross_v2 check (refunds_amount <= gross_ticket_revenue);

alter table public.growth_experiment_arms_v1
  add constraint growth_experiment_arms_experiment_id_id_unique_v2 unique (experiment_id,id);

create table if not exists private.growth_experiment_assignments_v1 (
  id bigint generated by default as identity primary key,
  experiment_id bigint not null references public.growth_experiments_v1(id) on delete cascade,
  arm_id bigint not null,
  subject_key_hash text not null check (subject_key_hash ~ '^[0-9a-f]{64}$'),
  assigned_at timestamptz not null,
  source_name text not null,
  source_record_key text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (experiment_id,subject_key_hash),
  unique (arm_id,source_record_key),
  foreign key (experiment_id,arm_id)
    references public.growth_experiment_arms_v1(experiment_id,id)
    on delete cascade
);
create index if not exists idx_growth_assignments_experiment_arm_v1
  on private.growth_experiment_assignments_v1(experiment_id,arm_id);
alter table private.growth_experiment_assignments_v1 enable row level security;
revoke all on private.growth_experiment_assignments_v1 from public,anon,authenticated;
grant select,insert,update,delete on private.growth_experiment_assignments_v1 to service_role;
grant usage,select on sequence private.growth_experiment_assignments_v1_id_seq to service_role;
grant usage on schema private to service_role;

create table if not exists public.growth_execution_batches_v1 (
  id bigint generated by default as identity primary key,
  experiment_id bigint not null references public.growth_experiments_v1(id) on delete cascade,
  source_name text not null,
  batch_key text not null,
  assignment_mode text not null check (assignment_mode in ('exact_manifest','aggregate_only')),
  observed_at timestamptz not null,
  treatment_assigned_count integer check (treatment_assigned_count is null or treatment_assigned_count >= 0),
  holdout_assigned_count integer check (holdout_assigned_count is null or holdout_assigned_count >= 0),
  assignment_rows_count integer not null default 0 check (assignment_rows_count >= 0),
  metrics_rows_count integer not null default 0 check (metrics_rows_count >= 0),
  payload_sha256 text not null check (payload_sha256 ~ '^[0-9a-f]{64}$'),
  metadata jsonb not null default '{}'::jsonb,
  accepted_at timestamptz not null default now(),
  unique (source_name,batch_key)
);
create index if not exists idx_growth_execution_batches_experiment_time_v1
  on public.growth_execution_batches_v1(experiment_id,observed_at desc);
