create or replace function public.ingest_growth_execution_batch_v2(p_payload jsonb)
returns jsonb
language plpgsql
security invoker
set search_path=public,private,pg_temp
as $$
declare
  v_experiment_key text := nullif(btrim(p_payload->>'experimentKey'),'');
  v_source_name text := nullif(btrim(p_payload->>'sourceName'),'');
  v_batch_key text := nullif(btrim(p_payload->>'batchKey'),'');
  v_assignment_mode text := coalesce(nullif(btrim(p_payload->>'assignmentMode'),''),'aggregate_only');
  v_payload_sha text := lower(coalesce(nullif(btrim(p_payload->>'payloadSha256'),''),''));
  v_actor text := coalesce(nullif(btrim(p_payload->>'actor'),''),nullif(btrim(p_payload->>'sourceName'),''),'growth-execution-ingest-v2');
  v_observed_at timestamptz;
  v_experiment_id bigint;
  v_experiment_status text;
  v_treatment_arm_id bigint;
  v_holdout_arm_id bigint;
  v_assignments jsonb := coalesce(p_payload->'assignments','[]'::jsonb);
  v_metrics jsonb := coalesce(p_payload->'arms','[]'::jsonb);
  v_assignment_rows integer := 0;
  v_metrics_rows integer := 0;
  v_treatment_manifest integer := 0;
  v_holdout_manifest integer := 0;
  v_existing_batch_id bigint;
  v_existing_hash text;
  v_item jsonb;
  v_arm_key text;
  v_arm_id bigint;
  v_subject_hash text;
  v_source_record_key text;
  v_assigned_at timestamptz;
  v_assigned integer;
  v_exposed integer;
  v_purchasers integer;
  v_tickets integer;
  v_gross numeric;
  v_refunds numeric;
  v_cost numeric;
  v_prev public.growth_experiment_arm_observations_v1%rowtype;
  v_treatment_assigned integer;
  v_holdout_assigned integer;
  v_rows_by_arm jsonb := '{}'::jsonb;
begin
  if v_experiment_key is null then raise exception 'experimentKey required'; end if;
  if v_source_name is null then raise exception 'sourceName required'; end if;
  if v_batch_key is null then raise exception 'batchKey required'; end if;
  if v_assignment_mode not in ('exact_manifest','aggregate_only') then raise exception 'assignmentMode must be exact_manifest or aggregate_only'; end if;
  if v_payload_sha !~ '^[0-9a-f]{64}$' then raise exception 'payloadSha256 must be 64 lowercase hex chars'; end if;
  begin
    v_observed_at := (p_payload->>'observedAt')::timestamptz;
  exception when others then
    raise exception 'valid observedAt required';
  end;
  if v_observed_at > now() + interval '5 minutes' then raise exception 'observedAt is in the future'; end if;

  select id,payload_sha256 into v_existing_batch_id,v_existing_hash
  from public.growth_execution_batches_v1
  where source_name=v_source_name and batch_key=v_batch_key;
  if v_existing_batch_id is not null then
    if v_existing_hash <> v_payload_sha then raise exception 'batchKey already exists with a different payload hash'; end if;
    return jsonb_build_object('ok',true,'duplicate',true,'batchId',v_existing_batch_id,'experimentKey',v_experiment_key);
  end if;

  select id,status into v_experiment_id,v_experiment_status
  from public.growth_experiments_v1
  where experiment_key=v_experiment_key
  for update;
  if v_experiment_id is null then raise exception 'experiment not found'; end if;
  if v_experiment_status not in ('planned','running','completed') then
    raise exception 'experiment must be planned, running or completed before execution data can be ingested';
  end if;

  select id into v_treatment_arm_id from public.growth_experiment_arms_v1 where experiment_id=v_experiment_id and arm_key='treatment';
  select id into v_holdout_arm_id from public.growth_experiment_arms_v1 where experiment_id=v_experiment_id and arm_key='holdout';
  if v_treatment_arm_id is null or v_holdout_arm_id is null then raise exception 'experiment requires treatment and holdout arms'; end if;

  if jsonb_typeof(v_assignments) <> 'array' then raise exception 'assignments must be an array'; end if;
  if jsonb_typeof(v_metrics) <> 'array' then raise exception 'arms must be an array'; end if;

  if v_assignment_mode='exact_manifest' then
    for v_item in select value from jsonb_array_elements(v_assignments)
    loop
      v_arm_key := nullif(btrim(v_item->>'armKey'),'');
      if v_arm_key not in ('treatment','holdout') then raise exception 'assignment armKey must be treatment or holdout'; end if;
      v_arm_id := case when v_arm_key='treatment' then v_treatment_arm_id else v_holdout_arm_id end;
      v_subject_hash := lower(coalesce(nullif(btrim(v_item->>'subjectKeyHash'),''),''));
      if v_subject_hash !~ '^[0-9a-f]{64}$' then raise exception 'subjectKeyHash must be 64 lowercase hex chars'; end if;
      v_source_record_key := coalesce(nullif(btrim(v_item->>'sourceRecordKey'),''),v_subject_hash);
      begin
        v_assigned_at := coalesce((v_item->>'assignedAt')::timestamptz,v_observed_at);
      exception when others then
        raise exception 'assignment assignedAt must be a valid timestamp';
      end;

      if exists (
        select 1 from private.growth_experiment_assignments_v1 x
        where x.experiment_id=v_experiment_id and x.subject_key_hash=v_subject_hash and x.arm_id<>v_arm_id
      ) then raise exception 'subject assignment cannot move between treatment and holdout'; end if;

      insert into private.growth_experiment_assignments_v1(
        experiment_id,arm_id,subject_key_hash,assigned_at,source_name,source_record_key,metadata
      ) values (
        v_experiment_id,v_arm_id,v_subject_hash,v_assigned_at,v_source_name,v_source_record_key,
        coalesce(v_item->'metadata','{}'::jsonb)
      ) on conflict (experiment_id,subject_key_hash) do nothing;
      v_assignment_rows := v_assignment_rows + 1;
    end loop;
  elsif jsonb_array_length(v_assignments)>0 then
    raise exception 'assignments are only accepted when assignmentMode=exact_manifest';
  end if;

  select count(*)::integer into v_treatment_manifest
  from private.growth_experiment_assignments_v1 where experiment_id=v_experiment_id and arm_id=v_treatment_arm_id;
  select count(*)::integer into v_holdout_manifest
  from private.growth_experiment_assignments_v1 where experiment_id=v_experiment_id and arm_id=v_holdout_arm_id;

  if jsonb_array_length(v_metrics)>0 and v_experiment_status not in ('running','completed') then
    raise exception 'arm metrics require a running or completed experiment';
  end if;

  for v_item in select value from jsonb_array_elements(v_metrics)
  loop
    v_arm_key := nullif(btrim(v_item->>'armKey'),'');
    if v_arm_key not in ('treatment','holdout') then raise exception 'metric armKey must be treatment or holdout'; end if;
    if v_rows_by_arm ? v_arm_key then raise exception 'only one metrics row per arm is allowed in a batch'; end if;
    v_rows_by_arm := v_rows_by_arm || jsonb_build_object(v_arm_key,true);
    v_arm_id := case when v_arm_key='treatment' then v_treatment_arm_id else v_holdout_arm_id end;

    begin
      v_assigned := (v_item->>'assignedCount')::integer;
      v_exposed := (v_item->>'exposedCount')::integer;
      v_purchasers := (v_item->>'purchasersCount')::integer;
      v_tickets := (v_item->>'ticketsCount')::integer;
      v_gross := (v_item->>'grossTicketRevenue')::numeric;
      v_refunds := coalesce((v_item->>'refundsAmount')::numeric,0);
      v_cost := coalesce((v_item->>'campaignCost')::numeric,0);
    exception when others then
      raise exception 'invalid numeric arm metrics';
    end;

    if v_assigned<0 or v_exposed<0 or v_purchasers<0 or v_tickets<0 then raise exception 'arm counts must be non-negative'; end if;
    if v_exposed>v_assigned then raise exception 'exposedCount may not exceed assignedCount'; end if;
    if v_purchasers>v_assigned then raise exception 'purchasersCount may not exceed assignedCount'; end if;
    if v_tickets<v_purchasers then raise exception 'ticketsCount may not be lower than purchasersCount'; end if;
    if v_gross<0 or v_refunds<0 or v_cost<0 then raise exception 'financial values must be non-negative'; end if;
    if v_refunds>v_gross then raise exception 'refundsAmount may not exceed grossTicketRevenue'; end if;

    if v_assignment_mode='exact_manifest' then
      if v_arm_key='treatment' and v_assigned<>v_treatment_manifest then raise exception 'treatment assignedCount does not match exact manifest'; end if;
      if v_arm_key='holdout' and v_assigned<>v_holdout_manifest then raise exception 'holdout assignedCount does not match exact manifest'; end if;
    end if;

    select * into v_prev
    from public.growth_experiment_arm_observations_v1
    where arm_id=v_arm_id order by observed_at desc,id desc limit 1;
    if v_prev.id is not null then
      if v_assigned<coalesce(v_prev.assigned_count,0) then raise exception 'cumulative assignedCount may not decrease'; end if;
      if v_exposed<v_prev.exposed_count then raise exception 'cumulative exposedCount may not decrease'; end if;
      if v_purchasers<v_prev.purchasers_count then raise exception 'cumulative purchasersCount may not decrease'; end if;
      if v_tickets<v_prev.tickets_count then raise exception 'cumulative ticketsCount may not decrease'; end if;
      if v_gross<v_prev.gross_ticket_revenue then raise exception 'cumulative grossTicketRevenue may not decrease'; end if;
      if v_refunds<v_prev.refunds_amount then raise exception 'cumulative refundsAmount may not decrease'; end if;
      if v_cost<v_prev.campaign_cost then raise exception 'cumulative campaignCost may not decrease'; end if;
      if v_observed_at<v_prev.observed_at then raise exception 'observedAt may not move backwards'; end if;
    end if;

    insert into public.growth_experiment_arm_observations_v1(
      arm_id,observed_at,assigned_count,assignment_manifest_count,exposed_count,purchasers_count,tickets_count,
      gross_ticket_revenue,refunds_amount,campaign_cost,data_source,source_record_key,metadata
    ) values (
      v_arm_id,v_observed_at,v_assigned,
      case when v_assignment_mode='exact_manifest' then case when v_arm_key='treatment' then v_treatment_manifest else v_holdout_manifest end else null end,
      v_exposed,v_purchasers,v_tickets,v_gross,v_refunds,v_cost,v_source_name,v_batch_key||':'||v_arm_key,
      coalesce(v_item->'metadata','{}'::jsonb) || jsonb_build_object('assignment_mode',v_assignment_mode,'batch_key',v_batch_key)
    ) on conflict (arm_id,source_record_key) do update set
      observed_at=excluded.observed_at,assigned_count=excluded.assigned_count,assignment_manifest_count=excluded.assignment_manifest_count,
      exposed_count=excluded.exposed_count,purchasers_count=excluded.purchasers_count,tickets_count=excluded.tickets_count,
      gross_ticket_revenue=excluded.gross_ticket_revenue,refunds_amount=excluded.refunds_amount,campaign_cost=excluded.campaign_cost,
      data_source=excluded.data_source,metadata=excluded.metadata;

    if v_arm_key='treatment' then v_treatment_assigned:=v_assigned; else v_holdout_assigned:=v_assigned; end if;
    v_metrics_rows:=v_metrics_rows+1;
  end loop;

  if v_metrics_rows not in (0,2) then raise exception 'metrics batches must include both treatment and holdout arms'; end if;
  if v_assignment_mode='aggregate_only' and v_metrics_rows<>2 then raise exception 'aggregate_only batches require both arm metrics'; end if;

  if v_assignment_mode='exact_manifest' then
    v_treatment_assigned:=coalesce(v_treatment_assigned,v_treatment_manifest);
    v_holdout_assigned:=coalesce(v_holdout_assigned,v_holdout_manifest);
  end if;

  insert into public.growth_execution_batches_v1(
    experiment_id,source_name,batch_key,assignment_mode,observed_at,treatment_assigned_count,holdout_assigned_count,
    assignment_rows_count,metrics_rows_count,payload_sha256,metadata
  ) values (
    v_experiment_id,v_source_name,v_batch_key,v_assignment_mode,v_observed_at,v_treatment_assigned,v_holdout_assigned,
    v_assignment_rows,v_metrics_rows,v_payload_sha,coalesce(p_payload->'metadata','{}'::jsonb)
  ) returning id into v_existing_batch_id;

  insert into public.growth_experiment_audit_log_v1(experiment_id,action,actor,note,payload)
  values (
    v_experiment_id,'execution_batch_ingested',v_actor,
    format('Execution batch %s accepted from %s',v_batch_key,v_source_name),
    jsonb_build_object('batch_id',v_existing_batch_id,'batch_key',v_batch_key,'source_name',v_source_name,
      'assignment_mode',v_assignment_mode,'assignment_rows',v_assignment_rows,'metrics_rows',v_metrics_rows,
      'treatment_assigned',v_treatment_assigned,'holdout_assigned',v_holdout_assigned)
  );

  return jsonb_build_object(
    'ok',true,'duplicate',false,'batchId',v_existing_batch_id,'experimentId',v_experiment_id,'experimentKey',v_experiment_key,
    'assignmentMode',v_assignment_mode,'assignmentRows',v_assignment_rows,'metricsRows',v_metrics_rows,
    'treatmentAssigned',v_treatment_assigned,'holdoutAssigned',v_holdout_assigned
  );
end;
$$;
revoke all on function public.ingest_growth_execution_batch_v2(jsonb) from public,anon,authenticated;
grant execute on function public.ingest_growth_execution_batch_v2(jsonb) to service_role;

