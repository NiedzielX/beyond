create or replace view public.dashboard_growth_experiment_measurement_v2
with (security_invoker=true)
as
with latest_obs as (
  select distinct on (o.arm_id)
    o.arm_id,o.observed_at,o.assigned_count,o.assignment_manifest_count,o.exposed_count,o.purchasers_count,o.tickets_count,
    o.gross_ticket_revenue,o.refunds_amount,o.campaign_cost,o.data_source
  from public.growth_experiment_arm_observations_v1 o
  order by o.arm_id,o.observed_at desc,o.id desc
), latest_batch as (
  select distinct on (b.experiment_id)
    b.experiment_id,b.source_name,b.assignment_mode,b.observed_at,b.treatment_assigned_count,b.holdout_assigned_count,b.metrics_rows_count
  from public.growth_execution_batches_v1 b
  order by b.experiment_id,b.observed_at desc,b.id desc
), p as (
  select
    e.id experiment_id,e.experiment_key,e.ticket_event_id,e.play,e.status,e.hypothesis,e.action_description,e.primary_metric,
    e.assignment_method,e.currency,e.min_assigned_per_arm,te.home_team,te.away_team,te.kickoff_at,
    max(case when a.arm_key='treatment' then a.planned_share_pct end) treatment_share_pct,
    max(case when a.arm_key='holdout' then a.planned_share_pct end) holdout_share_pct,
    coalesce(max(case when a.arm_key='treatment' then o.assigned_count end),max(lb.treatment_assigned_count)) treatment_assigned,
    coalesce(max(case when a.arm_key='holdout' then o.assigned_count end),max(lb.holdout_assigned_count)) holdout_assigned,
    max(case when a.arm_key='treatment' then o.assignment_manifest_count end) treatment_manifest_count,
    max(case when a.arm_key='holdout' then o.assignment_manifest_count end) holdout_manifest_count,
    max(case when a.arm_key='treatment' then o.observed_at end) treatment_observed_at,
    max(case when a.arm_key='holdout' then o.observed_at end) holdout_observed_at,
    max(case when a.arm_key='treatment' then o.exposed_count end) treatment_exposed,
    max(case when a.arm_key='holdout' then o.exposed_count end) holdout_exposed,
    max(case when a.arm_key='treatment' then o.purchasers_count end) treatment_purchasers,
    max(case when a.arm_key='holdout' then o.purchasers_count end) holdout_purchasers,
    max(case when a.arm_key='treatment' then o.tickets_count end) treatment_tickets,
    max(case when a.arm_key='holdout' then o.tickets_count end) holdout_tickets,
    max(case when a.arm_key='treatment' then o.gross_ticket_revenue end) treatment_gross_revenue,
    max(case when a.arm_key='holdout' then o.gross_ticket_revenue end) holdout_gross_revenue,
    max(case when a.arm_key='treatment' then o.refunds_amount end) treatment_refunds,
    max(case when a.arm_key='holdout' then o.refunds_amount end) holdout_refunds,
    max(case when a.arm_key='treatment' then o.campaign_cost end) treatment_campaign_cost,
    max(case when a.arm_key='holdout' then o.campaign_cost end) holdout_campaign_cost,
    max(case when a.arm_key='treatment' then o.data_source end) treatment_data_source,
    max(case when a.arm_key='holdout' then o.data_source end) holdout_data_source,
    max(lb.source_name) latest_batch_source,max(lb.assignment_mode) latest_assignment_mode,max(lb.observed_at) latest_batch_at,
    max(lb.metrics_rows_count) latest_batch_metrics_rows
  from public.growth_experiments_v1 e
  join public.ticket_events te on te.id=e.ticket_event_id
  join public.growth_experiment_arms_v1 a on a.experiment_id=e.id
  left join latest_obs o on o.arm_id=a.id
  left join latest_batch lb on lb.experiment_id=e.id
  group by e.id,e.experiment_key,e.ticket_event_id,e.play,e.status,e.hypothesis,e.action_description,e.primary_metric,
           e.assignment_method,e.currency,e.min_assigned_per_arm,te.home_team,te.away_team,te.kickoff_at
), c as (
  select p.*,
    case when treatment_assigned>0 then treatment_exposed::numeric/treatment_assigned end treatment_exposure_rate,
    case when holdout_assigned>0 then holdout_exposed::numeric/holdout_assigned end holdout_exposure_rate,
    case when treatment_assigned>0 then treatment_purchasers::numeric/treatment_assigned end treatment_conversion_rate_itt,
    case when holdout_assigned>0 then holdout_purchasers::numeric/holdout_assigned end holdout_conversion_rate_itt,
    case when treatment_assigned>0 then treatment_tickets::numeric/treatment_assigned end treatment_ticket_rate_itt,
    case when holdout_assigned>0 then holdout_tickets::numeric/holdout_assigned end holdout_ticket_rate_itt,
    case when treatment_assigned>0 then treatment_gross_revenue/treatment_assigned end treatment_gross_revenue_per_assigned,
    case when holdout_assigned>0 then holdout_gross_revenue/holdout_assigned end holdout_gross_revenue_per_assigned,
    case when treatment_assigned>0 then (treatment_gross_revenue-coalesce(treatment_refunds,0))/treatment_assigned end treatment_net_revenue_per_assigned,
    case when holdout_assigned>0 then (holdout_gross_revenue-coalesce(holdout_refunds,0))/holdout_assigned end holdout_net_revenue_per_assigned
  from p
)
select c.*,
  case
    when status='draft' then 'draft_not_started'
    when treatment_assigned is null or holdout_assigned is null then 'awaiting_assignment'
    when latest_assignment_mode='exact_manifest' and treatment_manifest_count is not null and treatment_manifest_count<>treatment_assigned then 'assignment_mismatch'
    when latest_assignment_mode='exact_manifest' and holdout_manifest_count is not null and holdout_manifest_count<>holdout_assigned then 'assignment_mismatch'
    when treatment_observed_at is null or holdout_observed_at is null then 'awaiting_outcome_data'
    when treatment_assigned<min_assigned_per_arm or holdout_assigned<min_assigned_per_arm then 'collecting_sample'
    when assignment_method='manual_noncausal' then 'descriptive_only'
    else 'experiment_observed'
  end measurement_status,
  case
    when latest_assignment_mode is null then 'not_received'
    when latest_assignment_mode='aggregate_only' then 'aggregate_only'
    when treatment_assigned is null or holdout_assigned is null then 'manifest_received'
    when coalesce(treatment_manifest_count,treatment_assigned)=treatment_assigned and coalesce(holdout_manifest_count,holdout_assigned)=holdout_assigned then 'manifest_complete'
    else 'manifest_mismatch'
  end assignment_status,
  case
    when assignment_method='randomized_holdout' then 'randomized_itt'
    when assignment_method='geo_holdout' then 'holdout_itt'
    when assignment_method='quasi_experimental' then 'quasi_experimental_itt'
    else 'noncausal'
  end evidence_design,
  case when treatment_assigned>0 and holdout_assigned>0 and treatment_observed_at is not null and holdout_observed_at is not null
    then (treatment_ticket_rate_itt-holdout_ticket_rate_itt)*treatment_assigned end incremental_tickets_treatment_population,
  case when treatment_assigned>0 and holdout_assigned>0 and treatment_observed_at is not null and holdout_observed_at is not null
    then (treatment_gross_revenue_per_assigned-holdout_gross_revenue_per_assigned)*treatment_assigned end incremental_gross_revenue,
  case when treatment_assigned>0 and holdout_assigned>0 and treatment_observed_at is not null and holdout_observed_at is not null
    then (treatment_net_revenue_per_assigned-holdout_net_revenue_per_assigned)*treatment_assigned end incremental_net_revenue,
  case when treatment_assigned>0 and holdout_assigned>0 and treatment_observed_at is not null and holdout_observed_at is not null
    then coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_assigned,0))*treatment_assigned end incremental_campaign_cost,
  case when treatment_assigned>0 and holdout_assigned>0 and treatment_observed_at is not null and holdout_observed_at is not null
    then ((treatment_net_revenue_per_assigned-holdout_net_revenue_per_assigned)*treatment_assigned)
      -(coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_assigned,0))*treatment_assigned) end incremental_contribution,
  case when treatment_assigned>0 and holdout_assigned>0 and treatment_observed_at is not null and holdout_observed_at is not null
      and (coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_assigned,0))*treatment_assigned)>0
    then (((treatment_net_revenue_per_assigned-holdout_net_revenue_per_assigned)*treatment_assigned)
      -(coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_assigned,0))*treatment_assigned))
      /(coalesce(treatment_campaign_cost,0)-(coalesce(holdout_campaign_cost,0)/nullif(holdout_assigned,0))*treatment_assigned)
  end roi_on_incremental_campaign_cost,
  case
    when status='draft' then 'Experiment is still a draft; no execution data should exist yet.'
    when treatment_assigned is null or holdout_assigned is null then 'Treatment/holdout assignment has not been received.'
    when treatment_observed_at is null or holdout_observed_at is null then 'Assignment is known; waiting for cumulative outcome metrics for both arms.'
    when treatment_assigned<min_assigned_per_arm or holdout_assigned<min_assigned_per_arm then 'Below the operational assigned-audience gate; uplift is directional only.'
    when assignment_method='manual_noncausal' then 'Descriptive comparison only; no causal claim allowed.'
    else 'Intent-to-treat uplift is available; statistical significance is not assessed in v2.'
  end interpretation_note
from c;
revoke all on public.dashboard_growth_experiment_measurement_v2 from public;
