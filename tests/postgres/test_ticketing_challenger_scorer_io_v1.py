"""PG16 parity contract for the ticketing challenger I/O scorer.

This runs only on a dedicated disposable localhost database. The fixture models
the legacy feature-store projection independently, then verifies the keyed
helper and scorer preserve its rows, point-in-time cutoff, and fan-out.
"""
from datetime import datetime, timedelta, timezone
import os
import json
from pathlib import Path
import unittest
from urllib.parse import urlparse

import psycopg

ROOT = Path(__file__).resolve().parents[2]
SQL_PATH = ROOT / "supabase/ops/ticketing_challenger_scorer_io_v1.sql"


class TicketingChallengerScorerIO(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        dsn = os.environ.get("TICKETING_CHALLENGER_SCORER_IO_TEST_DSN", "")
        target = urlparse(dsn)
        if (target.hostname not in {"127.0.0.1", "localhost"} or target.port != 55440
                or target.path != "/ticketing_challenger_scorer_io_v1_test"):
            raise RuntimeError("Only the dedicated localhost ticketing challenger scorer I/O test DB is allowed")
        cls.db = psycopg.connect(dsn, autocommit=True)
        version = int(cls.db.execute("show server_version_num").fetchone()[0])
        if not 160000 <= version < 170000:
            raise RuntimeError("PostgreSQL16 required")
        cls._bootstrap()

    @classmethod
    def tearDownClass(cls):
        cls.db.close()

    @classmethod
    def _bootstrap(cls):
        db = cls.db
        for role in ("anon", "authenticated", "service_role"):
            exists = db.execute("select 1 from pg_roles where rolname=%s", (role,)).fetchone()
            if not exists:
                db.execute(f'create role "{role}" nologin')
        db.execute("create schema if not exists private")
        db.execute("""
          drop function if exists public.score_ticketing_challenger_v1();
          drop function if exists private.ticketing_challenger_t24_features_io_v1(bigint[]);
          drop view if exists public.multiclub_feature_store_v4 cascade;
          drop function if exists public.get_live_features_v1_asof(bigint,timestamptz);
          drop table if exists public.context_ablation_predictions_v1 cascade;
          drop table if exists public.event_context_snapshots_v1 cascade;
          drop table if exists public.ticketing_challenger_models_v1 cascade;
          drop table if exists public.ticket_event_inventory_reference cascade;
          drop table if exists public.ticket_event_outcomes cascade;
          drop table if exists public.test_live_velocity cascade;
          drop table if exists public.snapshots cascade;
          drop table if exists public.ticket_events cascade;
          create table public.ticket_events(id bigint primary key, kickoff_at timestamptz);
          create table public.snapshots(
            id bigint primary key, ticket_event_id bigint not null,
            captured_at timestamptz not null, available_total integer
          );
          create index on public.snapshots(ticket_event_id,captured_at,id);
          create table public.test_live_velocity(
            ticket_event_id bigint not null, as_of_at timestamptz not null, velocity_6h numeric
          );
          create table public.ticket_event_outcomes(ticket_event_id bigint);
          create table public.ticket_event_inventory_reference(
            ticket_event_id bigint, reference_type text
          );
          create table public.event_context_snapshots_v1(
            id bigint primary key, ticket_event_id bigint not null,
            checkpoint_at timestamptz not null, checkpoint_code text not null,
            capture_mode text not null
          );
          create table public.context_ablation_predictions_v1(
            id bigint generated by default as identity primary key,
            snapshot_id bigint not null, variant_key text not null,
            predicted_p50 integer not null, prediction_method text,
            model_version text, metadata jsonb not null default '{}'::jsonb
          );
          create table public.ticketing_challenger_models_v1(
            model_version text, trained_at timestamptz, horizon text, status text,
            score_floor_ratio numeric, score_ceiling_ratio numeric,
            y_mean numeric, beta numeric, x_mean numeric, x_sd numeric
          );
          create function public.get_live_features_v1_asof(bigint,timestamptz)
          returns table(velocity_6h numeric) language plpgsql volatile as $$
          begin
            if $1=900 then raise exception 'UNEXPECTED_EXPENSIVE_FEATURE_LOOKUP'; end if;
            return query select v.velocity_6h from public.test_live_velocity v
              where v.ticket_event_id=$1 and v.as_of_at=$2;
          end $$;
        """)
        # Independent legacy-view projection: same source relations and formulas,
        # with the old event-key join and its source-row fan-out intact.
        db.execute("""
          create view public.multiclub_feature_store_v4 as
          with selected as (
            select e.id ticket_event_id,s.id snapshot_id,s.captured_at,s.available_total
            from public.ticket_events e
            cross join lateral (
              select x.id,x.captured_at,x.available_total from public.snapshots x
              where x.ticket_event_id=e.id and x.available_total is not null
                and x.captured_at<=e.kickoff_at
                and extract(epoch from (e.kickoff_at-x.captured_at))/3600.0 between 24 and 36
              order by (extract(epoch from (e.kickoff_at-x.captured_at))/3600.0-24),
                x.captured_at desc,x.id desc limit 1
            ) s where e.kickoff_at is not null
          ), features as (
            select s.ticket_event_id,s.snapshot_id,s.captured_at,
              round(lf.velocity_6h/nullif(first_s.available_total,0)*100.0,8) matched,
              case when anchor6.available_total is not null and s.captured_at>anchor6.captured_at then
                round((((anchor6.available_total-s.available_total)::numeric /
                    nullif(extract(epoch from (s.captured_at-anchor6.captured_at))/3600.0,0)) /
                    nullif(first_s.available_total,0)*100.0)::numeric,8)
              end raw
            from selected s
            left join lateral (
              select x.available_total from public.snapshots x
              where x.ticket_event_id=s.ticket_event_id and x.available_total is not null
                and x.captured_at<=s.captured_at order by x.captured_at asc,x.id asc limit 1
            ) first_s on true
            left join lateral (
              select x.captured_at,x.available_total from public.snapshots x
              where x.ticket_event_id=s.ticket_event_id and x.available_total is not null
                and x.captured_at<=s.captured_at-interval '6 hours'
              order by x.captured_at desc,x.id desc limit 1
            ) anchor6 on true
            left join lateral public.get_live_features_v1_asof(s.ticket_event_id,s.captured_at) lf on true
          )
          select f.ticket_event_id,'T-24h'::text horizon,f.snapshot_id,
            f.captured_at snapshot_captured_at,f.matched matched_velocity_6h_pct_of_first_per_hour,
            f.raw raw_velocity_6h_pct_of_first_per_hour
          from features f
          left join public.ticket_event_outcomes o on o.ticket_event_id=f.ticket_event_id
          left join public.ticket_event_inventory_reference r
            on r.ticket_event_id=f.ticket_event_id and r.reference_type='public_seat_map_size'
        """)
        db.execute(SQL_PATH.read_text())
        db.execute("grant usage on schema public,private to service_role,anon,authenticated")

    def setUp(self):
        self.db = psycopg.connect(os.environ["TICKETING_CHALLENGER_SCORER_IO_TEST_DSN"], autocommit=True)
        # Isolate each test's rows while retaining the installed SQL contract.
        self.db.execute("truncate public.context_ablation_predictions_v1 restart identity")
        self.db.execute("""truncate public.event_context_snapshots_v1, public.ticketing_challenger_models_v1,
          public.ticket_event_inventory_reference, public.ticket_event_outcomes,
          public.test_live_velocity, public.snapshots, public.ticket_events""")

    def tearDown(self):
        self.db.close()

    def _seed(self):
        db = self.db
        base = datetime(2026, 1, 1, tzinfo=timezone.utc)
        # 101 exercises tied snapshot IDs and duplicate label/reference fan-out.
        events = [(101, base+timedelta(days=2)), (102, base+timedelta(days=2)),
                  (103, base+timedelta(days=2)), (900, base+timedelta(days=2)),
                  (105, base+timedelta(days=2)), (106, base+timedelta(days=2))]
        db.cursor().executemany("insert into public.ticket_events values(%s,%s)", events)
        for event, kickoff in events:
            if event == 900:
                continue
            selected = kickoff-timedelta(hours=24)
            if event == 101:
                db.execute("insert into public.snapshots values(%s,%s,%s,1000)", (1010,event,kickoff-timedelta(hours=48)))
                db.cursor().executemany("insert into public.snapshots values(%s,%s,%s,%s)", [
                    (1011,event,selected,800), (1012,event,selected,700),
                    (1013,event,kickoff-timedelta(hours=30),900),
                    (1014,event,kickoff-timedelta(hours=30),850)])
                db.execute("insert into public.test_live_velocity values(%s,%s,25)", (event,selected))
                db.cursor().executemany("insert into public.ticket_event_outcomes values(%s)", [(event,),(event,)])
                db.cursor().executemany("insert into public.ticket_event_inventory_reference values(%s,'public_seat_map_size')", [(event,),(event,)])
            elif event == 102:
                db.execute("insert into public.snapshots values(%s,%s,%s,1000)", (1020,event,kickoff-timedelta(hours=48)))
                # Raw fallback: no live matched feature; same-time snapshot IDs
                # select the higher ID for the six-hour anchor.
                db.cursor().executemany("insert into public.snapshots values(%s,%s,%s,%s)", [
                    (1021,event,selected,600), (1022,event,kickoff-timedelta(hours=30),900),
                    (1023,event,kickoff-timedelta(hours=30),850)])
                db.execute("insert into public.ticket_event_outcomes values(%s)", (event,))
                db.execute("insert into public.ticket_event_inventory_reference values(%s,'public_seat_map_size')", (event,))
            elif event == 103:
                # Candidate snapshot with zero denominator and no matched value
                # yields a missing feature and must not score.
                db.execute("insert into public.snapshots values(%s,%s,%s,0)", (1031,event,selected))
            elif event == 105:
                # No 24-36h candidate, so helper output is absent.
                db.execute("insert into public.snapshots values(%s,%s,%s,500)", (1051,event,kickoff-timedelta(hours=20)))
            elif event == 106:
                # Candidate is knowable only after this issue's checkpoint.
                db.execute("insert into public.snapshots values(%s,%s,%s,1000)", (1060,event,kickoff-timedelta(hours=48)))
                db.cursor().executemany("insert into public.snapshots values(%s,%s,%s,%s)", [
                    (1061,event,selected,800),(1062,event,kickoff-timedelta(hours=30),900)])
        checkpoints = [
            (1001,101,base+timedelta(hours=24),'T-24h','prospective'),
            (1002,102,base+timedelta(hours=24),'T-24h','prospective'),
            (1003,103,base+timedelta(hours=24),'T-24h','prospective'),
            (1004,900,base+timedelta(hours=24),'T-24h','prospective'),
            (1005,105,base+timedelta(hours=24),'T-24h','prospective'),
            (1006,101,base+timedelta(hours=24),'T-24h','historical'),
            (1007,106,base+timedelta(hours=22),'T-24h','prospective'),
        ]
        db.cursor().executemany("insert into public.event_context_snapshots_v1 values(%s,%s,%s,%s,%s)", checkpoints)
        db.cursor().executemany("insert into public.context_ablation_predictions_v1(snapshot_id,variant_key,predicted_p50) values(%s,%s,%s)", [
            (1001,'baseline',10000),(1002,'baseline',9000),(1003,'baseline',8000),
            (1004,'baseline',7000),(1005,'baseline',6000),(1006,'baseline',5000),
            (1001,'contextual',9999),(1006,'baseline_ticketing',4444),
            (1007,'baseline',5500),
            (1004,'baseline_ticketing',3333)])
        db.execute("""insert into public.ticketing_challenger_models_v1 values
          ('fixture-model',%s,'T-24h','shadow_active',-0.25,0.25,0.02,0.1,0,1)""", (base-timedelta(days=1),))
        return base

    def test_helper_matches_legacy_rows_and_scorer_preserves_contract(self):
        self._seed()
        # Same source-view reference, ordered as a multiset: no DISTINCT or
        # one-row-per-event assumption is allowed at the helper boundary.
        ref = self.db.execute("""
          select ticket_event_id,snapshot_id,snapshot_captured_at,
            matched_velocity_6h_pct_of_first_per_hour,raw_velocity_6h_pct_of_first_per_hour
          from public.multiclub_feature_store_v4 where ticket_event_id=any(%s)
          order by 1,2,3,4,5
        """, ([101,102,103,105,106],)).fetchall()
        got = self.db.execute("""
          select ticket_event_id,snapshot_id,snapshot_captured_at,
            matched_velocity_6h_pct_of_first_per_hour,raw_velocity_6h_pct_of_first_per_hour
          from private.ticketing_challenger_t24_features_io_v1(%s)
          order by 1,2,3,4,5
        """, ([101,102,103,105,106],)).fetchall()
        self.assertEqual(got, ref)
        self.assertEqual(sum(row[0] == 101 for row in got), 4)
        self.assertEqual(next(row[1] for row in got if row[0] == 101), 1012)
        self.assertEqual(next(row[1] for row in got if row[0] == 102), 1021)
        self.assertIsNone(next(row[3] for row in got if row[0] == 102))
        self.assertIsNone(next(row[4] for row in got if row[0] == 103))
        self.assertFalse(any(row[0] == 105 for row in got))
        self.assertTrue(any(row[0] == 106 for row in got))

        expected = self.db.execute("""
          select s.id,'baseline_ticketing'::text,
            round((
              b.predicted_p50 * (1 + greatest(m.score_floor_ratio,least(m.score_ceiling_ratio,
                m.y_mean + m.beta * ((coalesce(f.matched_velocity_6h_pct_of_first_per_hour,
                  f.raw_velocity_6h_pct_of_first_per_hour)-m.x_mean)/nullif(m.x_sd,0)))))
            )::numeric)::int,
            'ticketing_challenger_v1_prospective_shadow'::text,m.model_version,
            jsonb_build_object('feature','hybrid_v6',
              'feature_value',coalesce(f.matched_velocity_6h_pct_of_first_per_hour,f.raw_velocity_6h_pct_of_first_per_hour),
              'feature_source',case when f.matched_velocity_6h_pct_of_first_per_hour is not null then 'matched_v6' else 'raw_v6' end,
              'feature_snapshot_id',f.snapshot_id,'feature_snapshot_captured_at',f.snapshot_captured_at,
              'model_trained_at',m.trained_at,'shadow_only',true)
          from public.event_context_snapshots_v1 s
          join public.context_ablation_predictions_v1 b on b.snapshot_id=s.id and b.variant_key='baseline'
          join public.multiclub_feature_store_v4 f on f.ticket_event_id=s.ticket_event_id and f.horizon='T-24h'
          join public.ticketing_challenger_models_v1 m on m.status='shadow_active' and m.horizon='T-24h'
          left join public.context_ablation_predictions_v1 existing
            on existing.snapshot_id=s.id and existing.variant_key='baseline_ticketing'
          where s.checkpoint_code='T-24h' and s.capture_mode='prospective' and m.trained_at<=s.checkpoint_at
            and f.snapshot_captured_at<=s.checkpoint_at
            and coalesce(f.matched_velocity_6h_pct_of_first_per_hour,f.raw_velocity_6h_pct_of_first_per_hour) is not null
            and existing.id is null
          order by s.id,3,6
        """).fetchall()
        before_id = self.db.execute("select coalesce(max(id),0) from public.context_ablation_predictions_v1").fetchone()[0]
        inserted = self.db.execute("select public.score_ticketing_challenger_v1()").fetchone()[0]
        actual = self.db.execute("""select snapshot_id,variant_key,predicted_p50,prediction_method,model_version,metadata
          from public.context_ablation_predictions_v1 where id>%s order by snapshot_id,predicted_p50,metadata""", (before_id,)).fetchall()
        self.assertEqual(inserted, 5)  # event 101's 2x2 source fan-out plus event 102 raw fallback
        self.assertEqual(inserted, len(expected))
        # Compare the full immutable business output, including rounded score,
        # model/version, selected source row, PIT timestamps, and metadata.
        normalize = lambda rows: sorted(
            [(r[0], r[1], r[2], r[3], r[4], json.dumps(r[5], sort_keys=True)) for r in rows],
            key=lambda r: (r[0], r[2], r[5]))
        self.assertEqual(normalize(actual), normalize(expected))
        self.assertEqual(sum(row[0] == 1001 for row in actual), 4)
        self.assertEqual(sum(row[0] == 1002 for row in actual), 1)
        self.assertFalse(any(row[0] == 1007 for row in actual))
        # Re-score sees only unresolved target variants; the existing and
        # out-of-scope candidates must not cause expensive feature resolution.
        self.assertEqual(self.db.execute("select public.score_ticketing_challenger_v1()").fetchone()[0], 0)

    def test_empty_due_set_does_not_touch_expensive_feature_lookup(self):
        self._seed()
        kickoff = self.db.execute("select kickoff_at from public.ticket_events where id=900").fetchone()[0]
        selected = kickoff-timedelta(hours=24)
        self.db.execute("insert into public.snapshots values(9001,900,%s,700)", (selected,))
        self.db.execute("insert into public.test_live_velocity values(900,%s,5)", (selected,))
        self.db.execute("delete from public.context_ablation_predictions_v1 where snapshot_id<>1004")
        self.db.execute("delete from public.event_context_snapshots_v1 where id<>1004")
        self.assertEqual(self.db.execute("select public.score_ticketing_challenger_v1()").fetchone()[0], 0)

    def test_guarded_rollback_restores_legacy_scorer(self):
        self._seed()
        self.db.execute("select public.score_ticketing_challenger_v1()")
        rollback = ROOT / "supabase/ops/ticketing_challenger_scorer_io_rollback_v1.sql"
        with self.db.transaction():
            self.db.execute(rollback.read_text())
        self.assertIsNone(self.db.execute(
            "select to_regprocedure('private.ticketing_challenger_t24_features_io_v1(bigint[])')"
        ).fetchone()[0])
        body = self.db.execute("select prosrc from pg_proc where oid='public.score_ticketing_challenger_v1()'::regprocedure").fetchone()[0]
        self.assertIn("public.multiclub_feature_store_v4", body)
        # Existing output rows remain and legacy rescoring sees no new work.
        self.assertEqual(self.db.execute("select public.score_ticketing_challenger_v1()").fetchone()[0], 0)
        # Leave the isolated DB in the forward version for repeated local runs.
        self.db.execute(SQL_PATH.read_text())


if __name__ == "__main__":
    unittest.main()
